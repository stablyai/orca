const { withAppBuildGradle } = require('expo/config-plugins')

// Why: Expo's template signs `release` with its public debug keystore. This adds a `release`
// signing config read from environment variables at build time, so no key or password is ever
// written into the generated project. Local release builds without the variables keep the debug
// key; once release signing is enabled, the release workflow sets ORCA_ANDROID_REQUIRE_RELEASE_SIGNING=true
// so a missing key fails the build instead of shipping a debug-signed APK.
const MARKER = 'orca: release signing'

const DEBUG_SIGNING_CONFIG = `        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
`

const RELEASE_SIGNING_CONFIG = `        // ${MARKER}, generated by plugins/android-release-signing.js.
        release {
            // v3 alongside v2 so a later key rotation can ship a signing-certificate lineage.
            enableV2Signing = true
            enableV3Signing = true
            def orcaKeystorePath = System.getenv('ORCA_ANDROID_KEYSTORE_PATH')
            if (orcaKeystorePath) {
                storeFile file(orcaKeystorePath)
                storePassword System.getenv('ORCA_ANDROID_KEYSTORE_PASSWORD')
                keyAlias System.getenv('ORCA_ANDROID_KEY_ALIAS')
                keyPassword System.getenv('ORCA_ANDROID_KEY_PASSWORD')
            }
        }
`

const RELEASE_BUILD_TYPE_SIGNING =
  /(\n        release \{\n(?:\s*\/\/[^\n]*\n)*)\s*signingConfig signingConfigs\.debug\n/

const RELEASE_SIGNING_SELECTION = `$1            signingConfig orcaReleaseSigningConfig(signingConfigs)
`

const RELEASE_SIGNING_HELPER = `
// ${MARKER}: pick the release key when its variables are set; required in the release workflow.
def orcaReleaseSigningConfig(signingConfigs) {
    def names = [
        'ORCA_ANDROID_KEYSTORE_PATH',
        'ORCA_ANDROID_KEYSTORE_PASSWORD',
        'ORCA_ANDROID_KEY_ALIAS',
        'ORCA_ANDROID_KEY_PASSWORD'
    ]
    def missing = names.findAll { !System.getenv(it) }
    def keystorePath = System.getenv('ORCA_ANDROID_KEYSTORE_PATH')
    if (missing.isEmpty() && !new File(keystorePath).isFile()) {
        missing = ["ORCA_ANDROID_KEYSTORE_PATH (no file at \${keystorePath})"]
    }
    if (missing.isEmpty()) {
        return signingConfigs.release
    }
    if (System.getenv('ORCA_ANDROID_REQUIRE_RELEASE_SIGNING') == 'true') {
        throw new GradleException(
            "Android release signing is required but not configured. Missing: \${missing.join(', ')}"
        )
    }
    if (missing.size() < names.size()) {
        throw new GradleException(
            "Android release signing is partially configured. Missing: \${missing.join(', ')}"
        )
    }
    return signingConfigs.debug
}
`

function patchAppBuildGradle(contents) {
  if (contents.includes(MARKER)) {
    return contents
  }
  // A changed template must fail prebuild rather than leave release builds on the debug key.
  if (!contents.includes(DEBUG_SIGNING_CONFIG) || !RELEASE_BUILD_TYPE_SIGNING.test(contents)) {
    throw new Error(
      "android-release-signing: Expo's app/build.gradle template changed; update the plugin before building."
    )
  }
  // Select first: the inserted signing config is also a `release {` block.
  const withSelection = contents.replace(RELEASE_BUILD_TYPE_SIGNING, RELEASE_SIGNING_SELECTION)
  const withSigningConfig = withSelection.replace(
    DEBUG_SIGNING_CONFIG,
    `${DEBUG_SIGNING_CONFIG}${RELEASE_SIGNING_CONFIG}`
  )
  return `${withSigningConfig.trimEnd()}\n${RELEASE_SIGNING_HELPER}`
}

module.exports = function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error(
        `android-release-signing: expected a Groovy app/build.gradle, got ${cfg.modResults.language}`
      )
    }
    cfg.modResults.contents = patchAppBuildGradle(cfg.modResults.contents)
    return cfg
  })
}

module.exports.patchAppBuildGradle = patchAppBuildGradle
