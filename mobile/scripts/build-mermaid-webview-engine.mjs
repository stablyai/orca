import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { createRequire } from 'node:module'
import { gzipSync } from 'node:zlib'
import * as esbuild from 'esbuild'

const require = createRequire(import.meta.url)
const mobileRoot = path.resolve(import.meta.dirname, '..')
const outputPath = path.join(
  mobileRoot,
  'src',
  'components',
  'pr-sidebar',
  'mermaid-webview-engine.generated.ts'
)

async function packageVersion(packageName) {
  let directory = path.dirname(require.resolve(packageName))
  for (;;) {
    try {
      const packageJson = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'))
      if (packageJson.name === packageName) {
        return `${packageName}@${packageJson.version}`
      }
    } catch {}
    const parent = path.dirname(directory)
    if (parent === directory) {
      throw new Error(`Unable to resolve ${packageName} package metadata`)
    }
    directory = parent
  }
}

function htmlScript(value) {
  return value.replace(/<\/script/gi, '<\\/script')
}

async function buildEngine() {
  const result = await esbuild.build({
    stdin: {
      contents: `
        import mermaid from 'mermaid'
        import DOMPurify from 'dompurify'
        window.OrcaMermaid = { mermaid, sanitize: DOMPurify.sanitize }
      `,
      resolveDir: mobileRoot,
      sourcefile: 'mermaid-webview-engine-entry.js'
    },
    bundle: true,
    format: 'iife',
    minify: true,
    platform: 'browser',
    target: 'safari15',
    legalComments: 'none',
    write: false,
    logLevel: 'silent'
  })
  return htmlScript(result.outputFiles[0].text)
}

async function main() {
  const [engine, mermaidVersion, domPurifyVersion] = await Promise.all([
    buildEngine(),
    packageVersion('mermaid'),
    packageVersion('dompurify')
  ])
  const hash = `'sha256-${createHash('sha256').update(engine).digest('base64')}'`
  const compressed = gzipSync(engine, { level: 9 }).toString('base64')
  const source = [
    '// Generated by scripts/build-mermaid-webview-engine.mjs.',
    `// Packages: ${mermaidVersion}, ${domPurifyVersion}. Do not edit by hand.`,
    `export const MERMAID_WEBVIEW_ENGINE_GZIP_BASE64 = ${JSON.stringify(compressed)}`,
    `export const MERMAID_WEBVIEW_ENGINE_CSP_HASH = ${JSON.stringify(hash)}`,
    ''
  ].join('\n')
  await writeFile(outputPath, source)
}

await main()
