import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { gzipSync } from 'node:zlib'

const mobileRoot = path.resolve(import.meta.dirname, '..')
const localesDir = path.join(mobileRoot, 'src', 'i18n', 'locales')
const outputDir = path.join(mobileRoot, 'src', 'i18n', 'locales-compressed')

const BUNDLED_LOCALES = ['de', 'es', 'fr', 'ja', 'ko', 'pt', 'ru', 'tr', 'zh', 'zh-Hant']

// Compress non-English catalogs into base64-gzipped ASCII strings so Hermes does not compile
// 68,000+ nested object properties and UTF-16 strings into bytecode for languages the user never opens.
async function main() {
  await mkdir(outputDir, { recursive: true })
  await Promise.all(
    BUNDLED_LOCALES.map(async (locale) => {
      const raw = await readFile(path.join(localesDir, `${locale}.json`), 'utf8')
      const minified = JSON.stringify(JSON.parse(raw))
      const encoded = gzipSync(Buffer.from(minified, 'utf8'), { level: 9 }).toString('base64')
      const source = [
        '// Generated by scripts/build-compressed-locale-catalogs.mjs.',
        `// Source: src/i18n/locales/${locale}.json (minified, gzip level 9, base64).`,
        '// Do not edit by hand; regenerate via pnpm postinstall.',
        `const catalogGzipBase64 = ${JSON.stringify(encoded)}`,
        'export default catalogGzipBase64',
        ''
      ].join('\n')
      await writeFile(path.join(outputDir, `${locale}.generated.ts`), source)
    })
  )
}

await main()
