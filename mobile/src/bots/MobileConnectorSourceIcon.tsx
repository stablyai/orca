/** A connector's logo in its brand colours, where the mark names the connector (its rows, setup, cards); the
 *  one-colour marks stay for glyphs beside text, as on the desktop. GitHub's brand mark is black or white. */
export function MobileConnectorLogo({
  source,
  size = 14
}: {
  source: ConnectorSource | 'google'
  size?: number
}) {
  useMobileColorScheme()
  if (source === 'slack' || source === 'google') {
    const side = source === 'google' ? 48 : 24
    return (
      <Svg width={size} height={size} viewBox={`0 0 ${side} ${side}`}>
        {(source === 'google' ? GOOGLE_PARTS : SLACK_PARTS).map(([fill, d]) => (
          <Path key={fill} d={d} fill={fill} />
        ))}
      </Svg>
    )
  }
  const side = SOURCE_ICON_VIEW_BOX[source]
  const fill =
    source === 'github' ? colors.textPrimary : source === 'linear' ? '#5E6AD2' : '#5865F2'
  return (
    <Svg width={size} height={size} viewBox={`0 0 ${side} ${side}`} fill={fill}>
      <Path d={SOURCE_PATHS[source]} />
    </Svg>
  )
}
