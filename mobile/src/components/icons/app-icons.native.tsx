import { SymbolView, type SymbolWeight } from 'expo-symbols'
import type { LucideProps } from 'lucide-react-native'
import type { AppIcon, NativeIconSymbol } from './app-icon-types'
import { asAppIcon } from './as-app-icon'
import { NATIVE_ICON_SYMBOLS, type NativeIconName } from './native-icon-symbols'
import { materialSymbol, sfSymbol } from './platform-symbol-names'

// Lucide draws 2 px strokes by default; SF Symbols take a weight instead.
function weightFor(strokeWidth: LucideProps['strokeWidth']): SymbolWeight {
  const width = Number(strokeWidth ?? 2)
  if (width <= 1.5) {
    return 'light'
  }
  return width <= 2 ? 'regular' : 'semibold'
}

function isFilled(fill: LucideProps['fill']): boolean {
  return fill !== undefined && fill !== 'none' && fill !== 'transparent'
}

function nativeIcon(name: NativeIconName): AppIcon {
  const [ios, android, iosFill]: readonly [string, string, string?] = NATIVE_ICON_SYMBOLS[name]
  const symbol: NativeIconSymbol = { ios, android, iosFill }
  function Icon({
    size = 24,
    color,
    strokeWidth,
    fill,
    style,
    pointerEvents,
    accessibilityLabel,
    testID
  }: LucideProps) {
    return (
      <SymbolView
        name={{
          ios: sfSymbol(isFilled(fill) && iosFill ? iosFill : ios),
          android: materialSymbol(android)
        }}
        size={Number(size)}
        tintColor={color}
        weight={weightFor(strokeWidth)}
        style={style}
        pointerEvents={pointerEvents}
        accessible={accessibilityLabel !== undefined}
        accessibilityLabel={accessibilityLabel}
        testID={testID}
      />
    )
  }
  Icon.displayName = name
  return asAppIcon(Icon, symbol)
}

