import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { isPluginSourceModulePath } from '../../shared/plugins/frames/plugin-frame-source-modules'
import { parsePluginManifest } from '../../shared/plugins/manifest/plugin-manifest'

/** Plugin-relative folder `orca plugin types` owns; dev hashing and loading skip it. */
export const PLUGIN_TYPES_DIR = '.orca/types'

/** Host, frame (`window.orca`), worker (`orca/worker`) and test kit (`orca/testing`) typings,
 *  under resources/plugins/types. */
const PLUGIN_SURFACE_TYPINGS = [
  { dir: 'orca-host', file: 'orca-host.d.ts' },
  { dir: 'orca-frame', file: 'orca-frame.d.ts' },
  { dir: 'orca-worker', file: 'orca-worker.d.ts' },
  { dir: 'orca-services', file: 'orca-services.d.ts' },
  { dir: 'orca-testing', file: 'orca-testing.d.ts' }
] as const

// Why one tsconfig the plugin extends: the typings and JSX settings then track the Orca that wrote
// them, and a plugin's own `include` cannot drop them (typeRoots resolve against this file).
const TYPES_TSCONFIG = {
  compilerOptions: {
    strict: true,
    noEmit: true,
    target: 'ES2022',
    module: 'ESNext',
    moduleResolution: 'Bundler',
    allowImportingTsExtensions: true,
    isolatedModules: true,
    jsx: 'react-jsx',
    jsxImportSource: 'orca',
    lib: ['ES2022', 'DOM'],
    // tsc 7 reaches `orca` via the symlinked path and the typeRoots via the realpath, so a plugin
    // under a symlink (macOS /tmp) loads the typings twice (TS2300 duplicate identifiers).
    preserveSymlinks: true,
    typeRoots: ['.'],
    types: ['orca', ...PLUGIN_SURFACE_TYPINGS.map(({ dir }) => dir)]
  }
}

/** The `orca` module's typings, split by size; written as one `orca/index.d.ts`. */
export const ORCA_MODULE_TYPINGS = [
  'orca.d.ts',
  'orca-components.d.ts',
  'orca-components-layout.d.ts',
  'orca-components-data.d.ts'
] as const

const GENERATED_NOTE =
  '// Written by `orca plugin types`; regenerated by `orca plugin dev load`. Do not edit.\n'

const defaultAppRoot = (): string => join(__dirname, '..', '..', '..')

/** Orca's author typings; `out/cli/plugin-authoring` and `src/cli/plugin-authoring` both sit
 *  three levels under the app root, and packaging unpacks resources/plugins/{declarative,types}. */
export async function readOrcaPluginTypings(appRoot = defaultAppRoot()): Promise<string> {
  const parts = await Promise.all(
    ORCA_MODULE_TYPINGS.map((file) =>
      readFile(join(appRoot, 'resources', 'plugins', 'declarative', file), 'utf8')
    )
  )
  return parts.join('\n')
}

/** Every typings file `orca plugin types` writes, keyed by its `.orca/types` folder. */
export async function readOrcaAuthorTypings(
  appRoot = defaultAppRoot()
): Promise<Record<string, string>> {
  const typings: Record<string, string> = { orca: await readOrcaPluginTypings(appRoot) }
  for (const { dir, file } of PLUGIN_SURFACE_TYPINGS) {
    typings[dir] = await readFile(join(appRoot, 'resources', 'plugins', 'types', file), 'utf8')
  }
  return typings
}

/** Writes `.orca/types/<folder>/index.d.ts` per typings file, a `tsconfig.json` listing them, and
 *  a `.gitignore` that ignores `.orca/`. */
export async function writePluginTypeFiles(pluginDir: string, appRoot?: string): Promise<string[]> {
  const typings = await readOrcaAuthorTypings(appRoot)
  const files: Record<string, string> = { '.orca/.gitignore': '*\n' }
  for (const [dir, text] of Object.entries(typings)) {
    await mkdir(join(pluginDir, '.orca', 'types', dir), { recursive: true })
    files[`${PLUGIN_TYPES_DIR}/${dir}/index.d.ts`] = GENERATED_NOTE + text
  }
  files[`${PLUGIN_TYPES_DIR}/tsconfig.json`] = `${JSON.stringify(TYPES_TSCONFIG, null, 2)}\n`
  for (const [file, content] of Object.entries(files)) {
    await writeFile(join(pluginDir, ...file.split('/')), content)
  }
  return Object.keys(files)
}

/** A folder gets typings on dev load when it has them, its tsconfig wants them, or it has a
 *  TS/TSX entry or a components panel. */
export async function pluginFolderWantsTypes(pluginDir: string): Promise<boolean> {
  if (existsSync(join(pluginDir, '.orca', 'types'))) {
    return true
  }
  const tsconfig = await readFile(join(pluginDir, 'tsconfig.json'), 'utf8').catch(() => '')
  if (tsconfig.includes(PLUGIN_TYPES_DIR)) {
    return true
  }
  const raw = await readFile(join(pluginDir, 'orca-plugin.json'), 'utf8').catch(() => null)
  let parsed: unknown = null
  try {
    parsed = raw === null ? null : JSON.parse(raw)
  } catch {
    return false
  }
  const manifest = parsePluginManifest(parsed)
  if (!manifest.ok) {
    return false
  }
  const { panels, customEditors } = manifest.manifest.contributes
  return (
    panels.some((panel) => panel.ui === 'components') ||
    [...panels, ...customEditors].some((item) => isPluginSourceModulePath(item.entry))
  )
}
