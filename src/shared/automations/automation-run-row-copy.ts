export type AutomationRunCopyKey = keyof typeof AUTOMATION_RUN_COPY

/** One phrase in the reader's language. */
export type SayAutomationRun = (
  key: AutomationRunCopyKey,
  params?: Record<string, string>
) => string

/** The phone's: English, with its values filled in. */
export function sayAutomationRunEnglish(
  key: AutomationRunCopyKey,
  params: Record<string, string> = {}
): string {
  return AUTOMATION_RUN_COPY[key].replace(/\{\{(\w+)\}\}/g, (_, name: string) => params[name] ?? '')
}
