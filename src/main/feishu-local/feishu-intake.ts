// Hands the owner's DM messages, oldest first, to the linked chat: a turn each, or a notice for a
// type Orca can't read. What no chat took waits in review.
import type { Bot } from '../../shared/bot-types'
import type { OrcaRuntimeService } from '../runtime/orca-runtime'
import { runtimeConversationHost } from '../external-conversations/external-conversation-runtime-host'
import { dmKey, type Binding } from './feishu-binding'
import { replyFeishu } from './feishu-replies'
import { feishuInput } from './feishu-resources'
import type { FeishuStore } from './feishu-store-ops'
import type { FeishuStream } from './feishu-stream'

export type FeishuIntake = {
  runtime: OrcaRuntimeService
  inbox: FeishuStore
  binding: Binding
  signal: AbortSignal
  bot: () => Bot | false | undefined
  checkProfile: () => Promise<void>
  /** The chat's delivery backlog is full; the rest waits for a later pass. */
  backlogFull: () => void
  changed: () => void
  stream: Pick<FeishuStream, 'open'>
}

const UNSUPPORTED_NAMES: Record<string, string> = {
  audio: 'voice',
  media: 'video',
  sticker: 'sticker',
  share_chat: 'shared group',
  share_user: 'shared contact',
  merge_forward: 'forwarded chat history'
}

function unsupportedNotice(type: string): string {
  const name = UNSUPPORTED_NAMES[type] ?? type.replace(/_/g, ' ')
  return `Orca can’t read ${name} messages yet, so this one didn’t reach the bot. Send text, a picture, a file, or a rich-text post instead.`
}

/** False when the pass stopped early (aborted, the bot gone), so no reply should be sent now. */
export async function drainFeishuInbox(intake: FeishuIntake): Promise<boolean> {
  const { runtime, inbox, binding: b, signal } = intake
  const seam = runtime.getExternalConversationSeam()
  if (!b.owner || !b.chat || !seam || !intake.bot()) {
    return false
  }
  const host = runtimeConversationHost(runtime)
  const key = dmKey(b)
  let row = await inbox.next(b.account)
  while (row && !signal.aborted) {
    if (row.kind !== 'text') {
      await intake.checkProfile()
    }
    const bot = intake.bot()
    if (!bot) {
      return false
    }
    if (row.kind === 'unsupported') {
      await replyFeishu(
        b.app,
        b.account,
        row.mid,
        b.chat,
        { type: 'text', content: { text: unsupportedNotice(row.type) } },
        'notice',
        signal
      ).catch(() => {})
      await inbox.admitted(b.account, row.mid)
      await inbox.finishReply(b.account, row.mid, false)
      row = await inbox.next(b.account)
      continue
    }
    // A DM whose chat was deleted in Orca opens a new one instead of being refused.
    if ((await seam.goneChats.linkedChatOf(host, key)) === 'gone') {
      seam.goneChats.release(key)
    }
    const { prompt, storedImages } = await feishuInput(inbox, b, row, bot.agent, signal)
    const { initial } = await seam.start(host, key, row.mid, {
      agent: bot.agent,
      transportSignal: signal,
      target: { kind: 'bot', botId: bot.id },
      prompt,
      note: 'If the owner asks you to create a small file, pipe its generated bytes into `orca bot reply --file-stdin <filename>` in this turn. The host attaches it to this DM. Never send an unrelated local file.',
      storedImages,
      asker: {
        userId: b.owner,
        role: 'owner',
        place: { kind: 'direct_message', id: b.chat },
        text: prompt,
        context: []
      },
      reply: { account: b.account }
    })
    if (signal.aborted) {
      return false
    }
    if (initial.outcome === 'refused' && initial.reason === 'delivery_backlog_full') {
      intake.backlogFull()
      break
    }
    if (initial.outcome === 'accepted') {
      await inbox.admitted(b.account, row.mid)
      if (intake.bot()) {
        await intake.stream.open(row.mid)
      }
    } else {
      // A refused message reached no chat and left no receipt, so Retry can deliver it again; one
      // whose fate is unknown may have run, so it can only be dismissed.
      if (initial.outcome === 'unknown') {
        await inbox.admitted(b.account, row.mid)
      }
      await inbox.review(b.account, row.mid)
      intake.changed()
    }
    row = await inbox.next(b.account)
  }
  return true
}
