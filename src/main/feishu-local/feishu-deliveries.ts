import type { OrcaRuntimeService } from '../runtime/orca-runtime'
import type { Bot } from '../../shared/bot-types'
import { runtimeConversationHost } from '../external-conversations/external-conversation-runtime-host'
import { dmKey, type Binding } from './feishu-binding'
import type { FeishuStore } from './feishu-store-ops'
import type { FeishuInteractions } from './feishu-interactions'
import { acknowledgeFeishuMessage } from './feishu-replies'
import { feishuInput } from './feishu-resources'

export async function deliverFeishuMessages(
  runtime: OrcaRuntimeService,
  inbox: FeishuStore,
  b: Binding,
  bot: Bot,
  signal: AbortSignal,
  active: () => boolean,
  checkProfile: () => Promise<void>,
  retry: () => void,
  changed: () => void,
  interactions: FeishuInteractions
) {
  const seam = runtime.getExternalConversationSeam()
  if (!seam || !b.owner || !b.chat) {
    return
  }
  const host = runtimeConversationHost(runtime)
  let row = await inbox.next(b.account)
  while (row && !signal.aborted && active()) {
    const route = await inbox.messageRoute(b.account, row.mid)
    const key = route ? { source: 'feishu-local' as const, externalId: route.external } : dmKey(b)
    if (row.kind !== 'text') {
      await checkProfile()
    }
    const { prompt, storedImages } = await feishuInput(
      inbox,
      route ? { ...b, chat: route.chat } : b,
      row,
      bot.agent,
      signal
    )
    const { initial } = await seam.start(host, key, row.mid, {
      agent: bot.agent,
      transportSignal: signal,
      target: { kind: 'bot', botId: bot.id },
      prompt,
      note: 'If the owner asks you to create a small file, pipe its generated bytes into `orca bot reply --file-stdin <filename>` in this turn. The host attaches it to this DM. Never send an unrelated local file.',
      storedImages,
      asker: {
        userId: b.owner,
        role: 'owner',
        place: route?.group
          ? { kind: 'channel', id: route.chat }
          : { kind: 'direct_message', id: b.chat },
        text: prompt,
        context: []
      },
      reply: { account: b.account }
    })
    if (signal.aborted) {
      return
    }
    if (initial.outcome === 'refused' && initial.reason === 'delivery_backlog_full') {
      retry()
      break
    }
    if (initial.outcome === 'accepted') {
      await acknowledgeFeishuMessage(inbox, b, row.mid, signal, () => Boolean(active()))
    } else {
      await inbox.review(b.account, row.mid)
      changed()
    }
    await inbox.admitted(b.account, row.mid)
    if (initial.outcome === 'accepted') {
      await interactions.status('feishu-local', key.externalId, '正在处理')
    }
    row = await inbox.next(b.account)
  }
}
