import type { OrcaRuntimeService } from '../runtime/orca-runtime'
import { runtimeConversationHost } from '../external-conversations/external-conversation-runtime-host'
import { dmKey, groupKey, type Binding } from './feishu-binding'
import type { FeishuTransport } from './feishu-transport'
import type { FeishuStore } from './feishu-store-ops'
import { feishuInput } from './feishu-resources'
import { acknowledgeFeishuMessage } from './feishu-replies'

export async function deliverFeishuInboxRow(
  runtime: OrcaRuntimeService,
  api: FeishuTransport,
  inbox: FeishuStore,
  binding: Binding,
  row: NonNullable<Awaited<ReturnType<FeishuStore['next']>>>,
  agent: string,
  signal: AbortSignal,
  active: () => boolean
) {
  const seam = runtime.getExternalConversationSeam()
  if (!seam || !binding.owner || !binding.chat) {
    return null
  }
  const { group } = row
  const { prompt, storedImages } = group
    ? { prompt: row.body, storedImages: [] }
    : await feishuInput(api, inbox, binding, row, agent, signal)
  if (signal.aborted || !active()) {
    return null
  }
  const key = group ? groupKey(binding, group) : dmKey(binding)
  const { initial } = await seam.start(runtimeConversationHost(runtime), key, row.mid, {
    agent,
    transportSignal: signal,
    target: { kind: 'bot', botId: binding.bot },
    prompt,
    ...(group
      ? {}
      : {
          note: 'If the owner asks you to create a small file, pipe its generated bytes into `orca bot reply --file-stdin <filename>` in this turn. The host attaches it to this DM. Never send an unrelated local file.'
        }),
    storedImages,
    asker: {
      userId: group?.sender ?? binding.owner,
      role: group ? 'member' : 'owner',
      place: group
        ? { kind: 'group_message', id: group.chatId }
        : { kind: 'direct_message', id: binding.chat },
      text: prompt,
      context: []
    },
    reply: { account: binding.account }
  })
  if (signal.aborted) {
    return null
  }
  if (initial.outcome === 'refused' && initial.reason === 'delivery_backlog_full') {
    return 'backlog'
  }
  if (initial.outcome === 'accepted') {
    await acknowledgeFeishuMessage(api, inbox, binding, row.mid, signal, active, group)
  } else {
    await (group && initial.outcome === 'refused'
      ? inbox.finishReply(binding.account, row.mid, true)
      : inbox.review(binding.account, row.mid))
  }
  await inbox.admitted(binding.account, row.mid)
  return initial.outcome === 'accepted' ? 'accepted' : 'review'
}
