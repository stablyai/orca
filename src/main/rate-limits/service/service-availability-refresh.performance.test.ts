beforeEach(() => {
  resetRateLimitProviderMocks()
  mockFreshBackgroundProviderFetches()
  vi.mocked(fetchActiveClaudeRateLimits).mockImplementation(async () => okProvider('claude', 31))
})

it.each([10, 100])(
  'keeps %s reconnects within the cooldown when other agents are unavailable',
  async (count) => {
    const service = new RateLimitService()
    service.setUsageProviderAvailabilityResolver(async (provider) => provider === 'claude')
    await service.refresh()
    for (let index = 0; index < count; index += 1) {
      await service.refreshIfStale()
    }
    expect(fetchActiveClaudeRateLimits).toHaveBeenCalledTimes(1)
    expect(fetchCodexRateLimits).toHaveBeenCalledTimes(0)
    expect((await service.getState()).claude?.session?.usedPercent).toBe(31)
    service.stop()
  }
)
