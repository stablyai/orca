// Answer the RPC host's idle-eviction probe from Pi's shared session-liveness registry. In-process
// hosts ask it before evicting; native chat runs Pi as a child, so the question arrives as a file in
// a private folder (never a prompt or dialog, which other extensions and the model would see) and
// the answer leaves as a status line.

import { getPiNativeWorkersBridgeSource } from './rpc-native-workers-bridge-source'

export const PI_BACKGROUND_WORK_STATUS_KEY = 'orca-background-work'
export const PI_BACKGROUND_WORK_DIR_ENV = 'ORCA_PI_BACKGROUND_WORK_DIR'
export const PI_BACKGROUND_WORK_BRIDGE_FILE = 'orca-background-work.ts'
export const PI_BACKGROUND_WORK_REQUEST_SUFFIX = '.probe'
const SESSION_LIVENESS_REGISTRY_KEY = '@agegr/pi-web/session-liveness/v1'

export function getPiBackgroundWorkBridgeSource(): string {
  return [
    `const REGISTRY = Symbol.for(${JSON.stringify(SESSION_LIVENESS_REGISTRY_KEY)})`,
    `const STATUS_KEY = ${JSON.stringify(PI_BACKGROUND_WORK_STATUS_KEY)}`,
    getPiNativeWorkersBridgeSource(),
    '',
    // Providers register in their own session_start, which can run before ours, so install at load.
    'function sessionLivenessRegistry() {',
    '  const existing = globalThis[REGISTRY]',
    "  if (existing && typeof existing === 'object' && existing.version === 1 && typeof existing.register === 'function' && typeof existing.hasActiveProvider === 'function') return existing",
    '  const providers = new Map()',
    '  const registry = {',
    '    version: 1,',
    '    register(provider) {',
    // Same v1 validation as the reference host, so a malformed registration cannot pin a session.
    "      const text = (value) => typeof value === 'string' && value.trim().length > 0",
    "      if (!provider || typeof provider !== 'object' || !text(provider.name) || !text(provider.sessionId) || (provider.sessionFile !== undefined && !text(provider.sessionFile)) || typeof provider.isActive !== 'function') throw new Error('Session liveness provider is invalid')",
    '      const key = Symbol(String(provider.name))',
    '      providers.set(key, provider)',
    '      let released = false',
    '      return () => {',
    '        if (released) return',
    '        released = true',
    '        providers.delete(key)',
    '      }',
    '    },',
    '    hasActiveProvider(session) {',
    '      const ids = new Set([session.sessionId, session.sessionFile].filter(Boolean))',
    '      for (const provider of providers.values()) {',
    '        if (!ids.has(provider.sessionId) && !(provider.sessionFile && ids.has(provider.sessionFile))) continue',
    // A failing or malformed provider preserves the session rather than releasing its work.
    '        try {',
    '          if (provider.isActive() !== false) return true',
    '        } catch {',
    '          return true',
    '        }',
    '      }',
    '      return false',
    '    }',
    '  }',
    '  globalThis[REGISTRY] = registry',
    '  return registry',
    '}',
    '',
    'export default function (pi) {',
    '  const registry = sessionLivenessRegistry()',
    `  const dir = process.env.${PI_BACKGROUND_WORK_DIR_ENV}`,
    '  let close = null',
    "  pi.on('session_start', (_event, ctx) => {",
    '    close?.()',
    '    close = null',
    '    if (!dir) return',
    "    const fs = require('fs')",
    "    const path = require('path')",
    // Each instance answers only requests named for it, so a reloaded predecessor cannot answer.
    "    const instance = require('crypto').randomUUID()",
    '    let live = true',
    '    const answer = () => {',
    '      if (!live) return',
    '      let names = []',
    '      try {',
    '        names = fs.readdirSync(dir)',
    '      } catch {',
    '        return',
    '      }',
    '      for (const name of names) {',
    `        if (!name.startsWith(instance + '.') || !name.endsWith(${JSON.stringify(PI_BACKGROUND_WORK_REQUEST_SUFFIX)})) continue`,
    `        const nonce = name.slice(instance.length + 1, -${PI_BACKGROUND_WORK_REQUEST_SUFFIX.length})`,
    '        try {',
    '          fs.rmSync(path.join(dir, name))',
    '        } catch {',
    '          continue',
    '        }',
    '        try {',
    '          const manager = ctx.sessionManager',
    '          const active = registry.hasActiveProvider({ sessionId: manager.getSessionId(), sessionFile: manager.getSessionFile() })',
    "          ctx.ui.setStatus(STATUS_KEY, 'answer:' + instance + ':' + nonce + (active ? ':active' : ':idle'))",
    '        } catch {}',
    '      }',
    '    }',
    // Watch events are only hints to rescan; a watcher that cannot start leaves the host without readiness.
    '    let watcher',
    '    try {',
    // The child makes its own folder, so a launch that never spawned leaves nothing behind.
    '      fs.mkdirSync(dir, { recursive: true })',
    '      watcher = fs.watch(dir, answer)',
    "      watcher.on('error', () => {})",
    '    } catch {',
    '      return',
    '    }',
    '    let closeWorkers = () => {}',
    '    close = () => {',
    '      live = false',
    '      closeWorkers()',
    '      try {',
    '        watcher.close()',
    '      } catch {}',
    '    }',
    '    try {',
    "      ctx.ui.setStatus(STATUS_KEY, 'ready:' + instance)",
    '    } catch {}',
    '    try { closeWorkers = observeNativeWorkers(pi, ctx, instance) } catch {}',
    '    answer()',
    '  })',
    "  pi.on('session_shutdown', (_event, ctx) => {",
    '    close?.()',
    '    close = null',
    '    try {',
    "      ctx.ui.setStatus(STATUS_KEY, 'gone')",
    '    } catch {}',
    '  })',
    '}',
    ''
  ].join('\n')
}
