export const ORCA_PI_DRAFT_BRIDGE_EXTENSION_FILE = 'orca-draft-bridge.ts'
export const ORCA_PI_DRAFT_BRIDGE_DIR_ENV = 'ORCA_PI_DRAFT_BRIDGE_DIR'
export const ORCA_PI_DRAFT_BRIDGE_TOKEN_ENV = 'ORCA_PI_DRAFT_BRIDGE_TOKEN'

const POLL_INTERVAL_MS = 40
const HEARTBEAT_INTERVAL_MS = 2000

/**
 * The in-process half of the terminal draft bridge. It is the only code allowed to read or write
 * Pi's real editor, so a host-side request can never be satisfied by guessing from screen output.
 * Commands and replies are files in the PTY's bridge dir; the host owns that dir's lifetime.
 */
export function getPiDraftBridgeExtensionSource(): string {
  return [
    'export default function (pi) {',
    "  const fs = require('node:fs')",
    "  const path = require('node:path')",
    "  const crypto = require('node:crypto')",
    `  const PROTOCOL = 1`,
    `  const dir = process.env['${ORCA_PI_DRAFT_BRIDGE_DIR_ENV}']`,
    `  const bridgeToken = process.env['${ORCA_PI_DRAFT_BRIDGE_TOKEN_ENV}']`,
    '  if (!dir || !bridgeToken) return',
    '  const requestPath = path.join(dir, "request.json")',
    '  const responsePath = path.join(dir, "response.json")',
    '  const helloPath = path.join(dir, "hello.json")',
    '  const startedAt = Date.now()',
    '  const instanceId = crypto.createHash("sha256").update(bridgeToken + ":" + process.pid + ":" + startedAt).digest("hex")',
    '  let ctx = null',
    '  let lastRequestId = null',
    '  let revision = 0',
    '  let lastText = null',
    '  let pollTimer = null',
    '  let heartbeatTimer = null',
    '  let unsubscribeInput = null',
    '',
    '  function hashText(text) {',
    '    return "pi:v2:" + instanceId + ":" + revision + ":" + crypto.createHash("sha256").update(text).digest("hex")',
    '  }',
    '',
    '  function readEditor() {',
    '    if (typeof ctx?.ui?.getEditorText !== "function") throw new Error("editor_read_unavailable")',
    '    const text = String(ctx.ui.getEditorText())',
    '    // Why: a content hash alone would let undo replay an old token; the revision fences that.',
    '    if (lastText === null) lastText = text',
    '    else if (text !== lastText) { revision += 1; lastText = text }',
    '    return text',
    '  }',
    '',
    '  function writeJsonAtomic(file, value) {',
    '    const tmp = file + "." + process.pid + ".tmp"',
    '    fs.writeFileSync(tmp, JSON.stringify(value))',
    '    try {',
    '      fs.renameSync(tmp, file)',
    '    } catch {',
    '      // Why: Windows can refuse rename-over-existing; the host accepts one direct rewrite.',
    '      fs.writeFileSync(file, JSON.stringify(value))',
    '      try { fs.unlinkSync(tmp) } catch {}',
    '    }',
    '  }',
    '',
    '  function sessionId() {',
    '    try { return String(ctx?.sessionManager?.getSessionId?.() ?? "") } catch { return "" }',
    '  }',
    '',
    '  function writeHello() {',
    '    const supported = typeof ctx?.ui?.getEditorText === "function" && typeof ctx?.ui?.setEditorText === "function"',
    '    writeJsonAtomic(helloPath, {',
    '      protocol: PROTOCOL, token: bridgeToken, instanceId, paneKey: process.env.ORCA_PANE_KEY ?? "",',
    '      pid: process.pid, sessionId: sessionId(), startedAt, at: Date.now(),',
    '      editor: "pi", capabilities: supported ? { capture: true, replace: true } : {}',
    '    })',
    '  }',
    '',
    '  function answer(request, value) {',
    '    writeJsonAtomic(responsePath, { protocol: PROTOCOL, token: bridgeToken, id: request.id, at: Date.now(), ...value })',
    '  }',
    '',
    '  function processRequest(request) {',
    '    if (!request || request.protocol !== PROTOCOL || request.token !== bridgeToken || typeof request.id !== "string") return',
    '    if (request.id === lastRequestId) return',
    '    lastRequestId = request.id',
    '    try {',
    '      const text = readEditor()',
    '      if (request.op === "capture") {',
    '        answer(request, { ok: true, text, sourceToken: hashText(text) })',
    '        return',
    '      }',
    '      if (request.op === "replace") {',
    '        if (typeof request.text !== "string") { answer(request, { ok: false, error: "invalid" }); return }',
    '        const currentToken = hashText(text)',
    '        if (request.baseToken !== currentToken) {',
    '          answer(request, { ok: false, error: "conflict", text, sourceToken: currentToken })',
    '          return',
    '        }',
    '        if (typeof ctx?.ui?.setEditorText !== "function") { answer(request, { ok: false, error: "unavailable" }); return }',
    '        ctx.ui.setEditorText(request.text)',
    '        const after = readEditor()',
    '        // Pi normalizes CRLF and tabs in setText; report the real text instead of pretending it matched.',
    '        answer(request, { ok: true, text: after, sourceToken: hashText(after), normalized: after !== request.text })',
    '        return',
    '      }',
    '      answer(request, { ok: false, error: "invalid" })',
    '    } catch {',
    '      answer(request, { ok: false, error: "unavailable" })',
    '    }',
    '  }',
    '',
    '  function poll() {',
    '    try { readEditor() } catch {}',
    '    try {',
    '      const raw = fs.readFileSync(requestPath, "utf8")',
    '      processRequest(JSON.parse(raw))',
    '    } catch {}',
    '  }',
    '',
    '  function stop() {',
    '    if (pollTimer) clearInterval(pollTimer)',
    '    if (heartbeatTimer) clearInterval(heartbeatTimer)',
    '    if (unsubscribeInput) unsubscribeInput()',
    '    pollTimer = null',
    '    heartbeatTimer = null',
    '    unsubscribeInput = null',
    '  }',
    '',
    '  function start(context) {',
    '    stop()',
    '    ctx = context',
    '    if (ctx?.mode !== "tui" || ctx?.hasUI === false) return',
    '    lastRequestId = null',
    '    // Why: raw input is the only signal that catches a change-and-undo between polls.',
    '    if (typeof ctx.ui.onTerminalInput === "function") {',
    '      unsubscribeInput = ctx.ui.onTerminalInput(() => { revision += 1; lastText = null })',
    '    }',
    '    writeHello()',
    `    pollTimer = setInterval(poll, ${POLL_INTERVAL_MS}); pollTimer.unref?.()`,
    `    heartbeatTimer = setInterval(writeHello, ${HEARTBEAT_INTERVAL_MS}); heartbeatTimer.unref?.()`,
    '  }',
    '',
    '  pi.on("session_start", async (_event, context) => start(context))',
    '  pi.on("session_shutdown", async () => stop())',
    '}',
    ''
  ].join('\n')
}
