import { describe, expect, it, vi } from 'vitest'
import { MARINE_CREATURES } from '../../../../../../shared/marine-creatures'
import { isAutoGeneratedCreatureBranchName } from '../../../../../../shared/branch-name-from-work'
import {
  creatureNameAtTier,
  creatureNameTier
} from '../../../../../../shared/worktree/retired-name-registry'
import { createWorkerWorktree, resolveWorkerWorktreeName } from './worker-worktree-creation'
import type { WorkerEffect } from './worker-topology'

const pool = MARINE_CREATURES.map((name) => name.toLowerCase())

function namingRuntime(livePaths: string[], retired: string[] = [], exhaustedTiers = 0) {
  return {
    listManagedWorktrees: vi.fn(async () => ({
      worktrees: livePaths.map((path) => ({ path }))
    })),
    listRetiredWorktreeNames: vi.fn(async () => ({
      retiredNamesByRepo: { repo: retired },
      retiredNameTiersByRepo: { repo: exhaustedTiers }
    }))
  }
}

describe('resolveWorkerWorktreeName', () => {
  it('keeps an explicit --name without generating one', async () => {
    const runtime = namingRuntime([])
    await expect(resolveWorkerWorktreeName(runtime, 'id:repo', 'billing-audit')).resolves.toEqual({
      name: 'billing-audit'
    })
    expect(runtime.listManagedWorktrees).not.toHaveBeenCalled()
  })

  it('picks the one creature name no live or retired workspace holds', async () => {
    const [free, ...taken] = pool
    const half = Math.floor(taken.length / 2)
    const runtime = namingRuntime(
      taken.slice(0, half).map((name) => `/worktrees/other-repo/${name}`),
      taken.slice(half)
    )
    await expect(resolveWorkerWorktreeName(runtime, 'id:repo', undefined)).resolves.toEqual({
      name: free,
      nameWasGenerated: true
    })
    expect(runtime.listRetiredWorktreeNames).toHaveBeenCalledWith('id:repo')
  })

  it('skips tiers the retired registry compacted as spent', async () => {
    const result = await resolveWorkerWorktreeName(namingRuntime([], [], 2), 'id:repo', undefined)
    expect(creatureNameTier(result.name)).toBe(3)
    expect(isAutoGeneratedCreatureBranchName(result.name)).toBe(true)
  })

  it('moves to the next tier once every first-tier name is used', async () => {
    const result = await resolveWorkerWorktreeName(namingRuntime([], pool), 'id:repo', undefined)
    expect(pool.map((name) => creatureNameAtTier(name, 2))).toContain(result.name)
  })
})

describe('createWorkerWorktree naming', () => {
  async function create(name: string | undefined) {
    const createManagedWorktree = vi.fn(async (_args: Record<string, unknown>) => ({
      worktree: { id: 'repo::/worktrees/repo/otter', repoId: 'repo', displayName: 'otter' },
      startupTerminal: { handle: 'term_worker' }
    }))
    const runtime = {
      ...namingRuntime([]),
      createManagedWorktree,
      listTerminals: vi.fn(async () => ({ terminals: [] }))
    }
    const effects: WorkerEffect[] = []
    await createWorkerWorktree({
      // oxlint-disable-next-line typescript/consistent-type-assertions -- SAFETY: createWorkerWorktree reaches only the runtime methods faked above.
      runtime: runtime as never,
      // oxlint-disable-next-line typescript/consistent-type-assertions -- SAFETY: createWorkerWorktree only records stages on the db.
      db: { recordWorkerStage: vi.fn() } as never,
      dispatchId: 'ctx_1',
      requestedWorktree: 'new-child',
      target: { repoSelector: 'id:repo', parentWorktreeId: 'repo::/repo' },
      params: { name, from: 'term_coord' },
      agent: 'codex',
      withAgentTerminal: true,
      effects
    })
    return { request: createManagedWorktree.mock.calls[0][0], effects }
  }

  it('creates a generated name the first-work rename may replace, and names it in effects', async () => {
    const { request, effects } = await create(undefined)
    expect(request.nameWasGenerated).toBe(true)
    expect(isAutoGeneratedCreatureBranchName(String(request.name))).toBe(true)
    expect(effects[0]).toEqual({
      kind: 'worktree',
      action: 'created_child',
      id: 'repo::/worktrees/repo/otter',
      name: 'otter'
    })
  })

  it('passes an explicit --name through as a user name', async () => {
    const { request } = await create('billing-audit')
    expect(request.name).toBe('billing-audit')
    expect(request).not.toHaveProperty('nameWasGenerated')
  })
})
