// The Orca-owned ssh_config and known_hosts behind `orca ssh` and the editors' Remote-SSH. Pure:
// the service writes what these return. ~/.ssh/config is only ever given one Include line, and
// only after the user agrees (see cloud-ssh-include.ts).

export type CloudSshHostEntry = {
  alias: string
  /** Absolute private key path. */
  identityFile: string
  user: string
  port: number
  /** `ssh-ed25519 <base64>`, pinned: the VM's host key comes from Orca's control plane. */
  hostKey: string
  /** Selector `orca ssh-proxy` resolves (the workspace's Orca Cloud environment). */
  proxyTarget: string
}

const ALIAS_PREFIX = 'orca-'

/** `orca-<workspace>-<4 id chars>`: readable in an editor's host list and unique per workspace. */
export function cloudSshAlias(workspaceName: string | undefined, uniqueId: string): string {
  const slug = (workspaceName ?? '')
    .normalize('NFKD')
    // Drop the accents NFKD split off, so "ünïcode" reads "unicode" rather than "u-ni-code".
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 32)
    .replace(/-+$/g, '')
  const suffix = uniqueId
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '')
    .slice(-4)
  return `${ALIAS_PREFIX}${slug || 'workspace'}-${suffix || '0000'}`
}

export function isCloudSshAlias(value: string): boolean {
  return /^orca-[a-z0-9-]{1,48}$/.test(value)
}

/** Key comments name the device and workspace so `authorized_keys` reads on its own. */
export function cloudSshKeyComment(deviceName: string, alias: string): string {
  const device =
    deviceName
      .toLowerCase()
      .replace(/[^a-z0-9.-]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 48) || 'desktop'
  return `orca:${device}:${alias}`
}

/** ssh_config values are double-quoted so paths with spaces (macOS userData) survive, and `%`
 *  doubled because ssh expands %-tokens in these keywords. */
function quote(value: string): string {
  // ProxyCommand runs through a shell: nothing that shell could expand inside double quotes.
  if (/["\r\n$`\\]/.test(value)) {
    throw new Error('ssh_config value cannot contain quotes, newlines, $, ` or \\')
  }
  return `"${value.replaceAll('%', '%%')}"`
}

export function renderCloudSshConfig(args: {
  entries: readonly CloudSshHostEntry[]
  knownHostsFile: string
  /** The `orca` CLI launcher this app runs as ProxyCommand. */
  cliCommand: string
  /** Pins ProxyCommand to this app's profile (dev and release can both be installed). POSIX only. */
  userDataPath?: string
}): string {
  const lines = [
    '# Generated by Orca for Orca Cloud workspaces. Edits are overwritten.',
    '# Each host tunnels through `orca ssh-proxy`, which wakes the workspace if it sleeps.',
    ''
  ]
  for (const entry of args.entries) {
    if (!isCloudSshAlias(entry.alias)) {
      continue
    }
    lines.push(
      `Host ${entry.alias}`,
      // Never dialled: ProxyCommand carries the connection. HostKeyAlias pins the key per alias.
      '  HostName 127.0.0.1',
      `  Port ${entry.port}`,
      `  User ${entry.user}`,
      `  HostKeyAlias ${entry.alias}`,
      `  IdentityFile ${quote(entry.identityFile)}`,
      '  IdentitiesOnly yes',
      '  IdentityAgent none',
      `  UserKnownHostsFile ${quote(args.knownHostsFile)}`,
      '  StrictHostKeyChecking yes',
      '  PasswordAuthentication no',
      // Agents in the VM must never reach the user's local ssh-agent or display.
      '  ForwardAgent no',
      '  ForwardX11 no',
      '  KbdInteractiveAuthentication no',
      `  ProxyCommand ${args.userDataPath ? `env ORCA_USER_DATA_PATH=${quote(args.userDataPath)} ` : ''}${quote(args.cliCommand)} ssh-proxy ${entry.proxyTarget}`,
      '  ServerAliveInterval 30',
      '  ServerAliveCountMax 4',
      ''
    )
  }
  return lines.join('\n')
}

export function renderCloudSshKnownHosts(entries: readonly CloudSshHostEntry[]): string {
  return entries
    .filter((entry) => isCloudSshAlias(entry.alias))
    .map((entry) => `${entry.alias} ${entry.hostKey}\n`)
    .join('')
}

/** One line a user can paste: needs no edit to ~/.ssh/config. */
export function cloudSshCommandLine(configFile: string, alias: string): string {
  return `ssh -F ${shellQuote(configFile)} ${alias}`
}

function shellQuote(value: string): string {
  return /^[A-Za-z0-9_./:@-]+$/.test(value) ? value : `'${value.replace(/'/g, `'\\''`)}'`
}
