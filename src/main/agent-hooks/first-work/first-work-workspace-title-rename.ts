type DisplayNameUpdate = { changed: boolean; log: string }

export function firstWorkNamingContext(
  settings: ReturnType<FirstWorkBranchRenameDeps['getSettings']>,
  context: BranchNameWorkContext,
  includeWorkspaceTitle = true
): BranchNameWorkContext {
  const workspaceTitleLanguage = includeWorkspaceTitle
    ? resolveWorkspaceTitleLanguage(
        settings,
        (hasAppEnvironment() ? getAppEnvironment().getSystemLocale?.() : undefined) ??
          Intl.DateTimeFormat().resolvedOptions().locale
      )
    : undefined
  return workspaceTitleLanguage ? { ...context, workspaceTitleLanguage } : context
}

export function runFolderWorkspaceTitleAutoRename(
  worktreeId: string,
  source: FirstWorkContextSource,
  deps: FirstWorkBranchRenameDeps,
  attempt: FirstWorkAttempt,
  verdicts: FirstWorkVerdictBuilders
): Promise<FirstWorkRenameVerdict> {
  return runWorkspaceTitleAutoRename(
    worktreeId,
    deps.getFolderWorkspacePath?.(worktreeId),
    undefined,
    source,
    deps,
    attempt,
    verdicts
  )
}

export function canRenamePendingWorkspaceTitle(
  worktreeId: string,
  deps: FirstWorkBranchRenameDeps
): boolean {
  return (
    shouldAutoRenameWorkspaceTitle(deps.getSettings()) &&
    deps.isPendingFirstAgentMessageRename?.(worktreeId) === true
  )
}

export function canRenameFirstWorkDisplayName(
  worktreeId: string,
  deps: FirstWorkBranchRenameDeps
): boolean {
  if (shouldAutoRenameWorkspaceTitle(deps.getSettings())) {
    return canRenamePendingWorkspaceTitle(worktreeId, deps)
  }
  const displayName = deps.getCurrentDisplayName(worktreeId)
  return !displayName || isAutoGeneratedCreatureBranchName(displayName)
}

/** Captures the pre-generation name so a manual rename during generation is preserved. */
export function prepareFirstWorkDisplayNameUpdate(
  worktreeId: string,
  repo: Repo,
  deps: FirstWorkBranchRenameDeps
): {
  update: (branchLeaf: string, generatedDisplayName: string | undefined) => DisplayNameUpdate
  keepBranch: (
    verdict: FirstWorkRenameVerdict,
    branchLeaf: string,
    generatedDisplayName: string | undefined
  ) => FirstWorkRenameVerdict
} {
  const originalDisplayName = deps.getCurrentDisplayName(worktreeId)
  const canRename = canRenameFirstWorkDisplayName(worktreeId, deps)
  const update = (
    branchLeaf: string,
    generatedDisplayName: string | undefined
  ): DisplayNameUpdate => {
    const currentDisplayName = deps.getCurrentDisplayName(worktreeId)
    if (
      !canRename ||
      currentDisplayName !== originalDisplayName ||
      !canRenameFirstWorkDisplayName(worktreeId, deps) ||
      (generatedDisplayName !== undefined && !canRenamePendingWorkspaceTitle(worktreeId, deps))
    ) {
      return { changed: false, log: `display kept ("${currentDisplayName}")` }
    }
    const newDisplayName = generatedDisplayName ?? humanizeBranchSlug(branchLeaf)
    deps.setDisplayName(worktreeId, newDisplayName)
    return { changed: true, log: `display "${currentDisplayName ?? ''}" -> "${newDisplayName}"` }
  }
  return {
    update,
    // The branch stays put, but a pending localized title can still land.
    keepBranch: (verdict, branchLeaf, generatedDisplayName) => {
      if (
        !generatedDisplayName ||
        !deps.getSettings().autoRenameBranchFromWork ||
        isWslMoveRepoBlocked(repo)
      ) {
        return verdict
      }
      const display = update(branchLeaf, generatedDisplayName)
      if (!display.changed) {
        return verdict
      }
      deps.setRenameError(worktreeId, null)
      deps.onRenamed(repo.id)
      console.info(`[auto-branch-rename] kept branch for ${worktreeId}; ${display.log}`)
      return { outcome: { kind: 'renamed' }, settles: true }
    }
  }
}

/** Names only the workspace title: folder workspaces, or worktrees whose branch must stay put. */
export async function runWorkspaceTitleAutoRename(
  worktreeId: string,
  workspacePath: string | undefined,
  repo: Repo | undefined,
  source: FirstWorkContextSource,
  deps: FirstWorkBranchRenameDeps,
  attempt: FirstWorkAttempt,
  verdicts: FirstWorkVerdictBuilders
): Promise<FirstWorkRenameVerdict> {
  const { stop, defer, failed } = verdicts
  const isBlocked = (): boolean =>
    repo ? isWslMoveRepoBlocked(repo) : deps.isFolderWorkspaceWslMoveBlocked?.(worktreeId) === true
  if (isBlocked()) {
    return defer('project-moving', 'a WSL move is taking the workspace')
  }
  if (deps.isPendingFirstAgentMessageRename?.(worktreeId) !== true) {
    return stop('already-named', 'workspace is not pending title rename', true)
  }
  if (!workspacePath) {
    return stop('unavailable', 'workspace path unavailable')
  }

  const originalDisplayName = deps.getCurrentDisplayName(worktreeId)
  const settings = deps.getSettings()
  const resolvedParams = resolveTextGenerationParams(settings, 'local', 'branchName', repo ?? null)
  if (!resolvedParams.ok) {
    deps.setRenameError(worktreeId, resolvedParams.error)
    return failed(`no generation agent: ${resolvedParams.error}`, true)
  }
  const resolved = await resolveFirstWorkContext(source, attempt)
  if (resolved.kind === 'outcome') {
    return { outcome: resolved.outcome, settles: false }
  }
  const target = await resolveGenerationTarget(workspacePath, resolvedParams.params.agentId, deps)
  if (!target) {
    deps.setRenameError(worktreeId, 'Could not prepare the workspace-name generation environment.')
    return failed('could not prepare generation environment', false)
  }

  // Target preparation awaits; a replaced workspace must not launch generation.
  attempt.assertIncarnation()
  const generated = await generateBranchNameFromContext(
    { ...firstWorkNamingContext(settings, resolved.context), workspaceTitleOnly: true },
    resolvedParams.params,
    target
  )
  // Generation may outlive a manual rename or workspace removal.
  if (
    deps.isPendingFirstAgentMessageRename?.(worktreeId) !== true ||
    deps.getCurrentDisplayName(worktreeId) !== originalDisplayName
  ) {
    return stop('already-named', 'workspace changed during generation', true)
  }
  if (isBlocked()) {
    return defer('project-moving', 'a WSL move started during generation')
  }
  if (!generated.success) {
    return failedGenerationVerdict(worktreeId, generated, deps, verdicts)
  }
  if (!deps.getSettings().autoRenameBranchFromWork) {
    return {
      ...stop('setting-off', 'auto-rename was turned off during generation'),
      settles: false
    }
  }

  const newDisplayName = generated.displayName ?? humanizeBranchSlug(generated.slug)
  deps.setDisplayName(worktreeId, newDisplayName)
  deps.setRenameError(worktreeId, null)
  deps.onRenamed(repo?.id ?? worktreeId)
  console.info(`[auto-branch-rename] renamed workspace title -> "${newDisplayName}"`)
  return { outcome: { kind: 'renamed' }, settles: true }
}
