import { retryFailedGeneration } from './first-work-generation-backoff'

export function firstWorkNamingContext(
  settings: ReturnType<FirstWorkBranchRenameDeps['getSettings']>,
  firstPrompt: string,
  assistantMessage: string | undefined,
  includeWorkspaceTitle = true
): BranchNameWorkContext {
  const workspaceTitleLanguage = includeWorkspaceTitle
    ? resolveWorkspaceTitleLanguage(
        settings,
        (hasAppEnvironment() ? getAppEnvironment().getSystemLocale?.() : undefined) ??
          Intl.DateTimeFormat().resolvedOptions().locale
      )
    : undefined
  return {
    firstPrompt,
    assistantMessage,
    ...(workspaceTitleLanguage ? { workspaceTitleLanguage } : {})
  }
}

export async function runFolderWorkspaceTitleAutoRename(
  worktreeId: string,
  prompt: string,
  assistantMessage: string | undefined,
  deps: FirstWorkBranchRenameDeps,
  stop: (reason: string, clearError?: boolean) => true,
  retry: (reason: string) => false
): Promise<boolean> {
  const folderPath = deps.getFolderWorkspacePath?.(worktreeId)
  if (!folderPath) {
    return stop('folder workspace path unavailable')
  }
  return runWorkspaceTitleAutoRename(
    worktreeId,
    folderPath,
    undefined,
    prompt,
    assistantMessage,
    deps,
    stop,
    retry
  )
}

function canRenamePendingWorkspaceTitle(
  worktreeId: string,
  deps: FirstWorkBranchRenameDeps
): boolean {
  return (
    shouldAutoRenameWorkspaceTitle(deps.getSettings()) &&
    deps.isPendingFirstAgentMessageRename?.(worktreeId) === true
  )
}

export function canRenameFirstWorkDisplayName(
  worktreeId: string,
  deps: FirstWorkBranchRenameDeps
): boolean {
  if (shouldAutoRenameWorkspaceTitle(deps.getSettings())) {
    return canRenamePendingWorkspaceTitle(worktreeId, deps)
  }
  const displayName = deps.getCurrentDisplayName(worktreeId)
  return !displayName || isAutoGeneratedCreatureBranchName(displayName)
}

export function prepareFirstWorkDisplayNameUpdate(
  worktreeId: string,
  deps: FirstWorkBranchRenameDeps
): (branchLeaf: string, generatedDisplayName: string | undefined) => string {
  const originalDisplayName = deps.getCurrentDisplayName(worktreeId)
  const canRename = canRenameFirstWorkDisplayName(worktreeId, deps)
  return (branchLeaf, generatedDisplayName) => {
    const currentDisplayName = deps.getCurrentDisplayName(worktreeId)
    if (
      !canRename ||
      currentDisplayName !== originalDisplayName ||
      !canRenameFirstWorkDisplayName(worktreeId, deps)
    ) {
      return `display kept ("${currentDisplayName}")`
    }
    const newDisplayName = generatedDisplayName ?? humanizeBranchSlug(branchLeaf)
    deps.setDisplayName(worktreeId, newDisplayName)
    return `display "${currentDisplayName ?? ''}" -> "${newDisplayName}"`
  }
}

export async function runWorkspaceTitleAutoRename(
  worktreeId: string,
  workspacePath: string,
  repo: Repo | undefined,
  prompt: string,
  assistantMessage: string | undefined,
  deps: FirstWorkBranchRenameDeps,
  stop: (reason: string, clearError?: boolean) => true,
  retry: (reason: string) => false
): Promise<boolean> {
  if (repo && !canRenamePendingWorkspaceTitle(worktreeId, deps)) {
    return stop('workspace is not pending a localized title', true)
  }
  if (deps.isPendingFirstAgentMessageRename?.(worktreeId) !== true) {
    return stop('workspace is not pending title rename', true)
  }
  const isBlocked = (): boolean =>
    repo ? isWslMoveRepoBlocked(repo) : deps.isFolderWorkspaceWslMoveBlocked?.(worktreeId) === true
  if (isBlocked()) {
    return retry('a WSL move is taking the workspace')
  }

  const originalDisplayName = deps.getCurrentDisplayName(worktreeId)
  const settings = deps.getSettings()
  const resolvedParams = resolveTextGenerationParams(settings, 'local', 'branchName', repo ?? null)
  if (!resolvedParams.ok) {
    deps.setRenameError(worktreeId, resolvedParams.error)
    return stop(`no generation agent: ${resolvedParams.error}`)
  }
  const target = await resolveGenerationTarget(workspacePath, resolvedParams.params.agentId, deps)
  if (!target) {
    deps.setRenameError(worktreeId, 'Could not prepare the workspace-name generation environment.')
    return retry('could not prepare generation environment')
  }

  const generated = await generateBranchNameFromContext(
    { ...firstWorkNamingContext(settings, prompt, assistantMessage), workspaceTitleOnly: true },
    resolvedParams.params,
    target
  )
  // Generation may outlive a manual rename or workspace removal.
  if (
    deps.isPendingFirstAgentMessageRename?.(worktreeId) !== true ||
    deps.getCurrentDisplayName(worktreeId) !== originalDisplayName
  ) {
    return stop('workspace changed during generation', true)
  }
  if (isBlocked()) {
    return retry('a WSL move started during generation')
  }
  if (!generated.success) {
    return retryFailedGeneration(worktreeId, generated, deps, retry)
  }

  const newDisplayName = generated.displayName ?? humanizeBranchSlug(generated.slug)
  deps.setDisplayName(worktreeId, newDisplayName)
  deps.setRenameError(worktreeId, null)
  deps.onRenamed(repo?.id ?? worktreeId)
  console.info(`[auto-branch-rename] renamed workspace title -> "${newDisplayName}"`)
  return true
}
