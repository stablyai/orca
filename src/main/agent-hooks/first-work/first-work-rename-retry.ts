export const FIRST_WORK_RETRY_LOOKUP_DEADLINE_MS = 10_000

export type FirstWorkRetryDeps = FirstWorkBranchRenameDeps & {
  /** When this workspace incarnation was created; messages before it never qualify. */
  getWorkspaceCreatedAt: (worktreeId: string) => number | undefined
  getBaseRef: (worktreeId: string) => string | undefined
  nativeReads: (worktreeId: string) => NativeFirstMessageReads
  runGit?: Parameters<typeof readBranchChangesForNaming>[0]['runGit']
}

const unreadable: FirstWorkContextResolution = {
  kind: 'outcome',
  outcome: { kind: 'deferred', reason: 'history-unreadable' }
}

/** Manual Try again: skips the settled cache and backoff, joins a running attempt for the same incarnation. */
export async function retryFirstWorkRename(
  worktreeId: string,
  deps: FirstWorkRetryDeps
): Promise<BranchAutoRenameRetryResult> {
  const now = () => Date.now()
  if (!deps.getSettings().autoRenameBranchFromWork) {
    return {
      attemptId: null,
      outcome: { kind: 'ineligible', reason: 'setting-off' },
      finishedAt: now()
    }
  }
  const incarnation = deps.readIncarnation(worktreeId)
  if (!incarnation) {
    return {
      attemptId: null,
      outcome: { kind: 'ineligible', reason: 'unavailable' },
      finishedAt: now()
    }
  }
  const running = runningFirstWorkAttempt(worktreeId, incarnation)
  if (running) {
    return running.promise
  }
  return startFirstWorkAttempt(
    worktreeId,
    incarnation,
    (attempt) =>
      runFirstWorkRename(
        worktreeId,
        lookupSource(worktreeId, incarnation, attempt, deps),
        deps,
        attempt
      ),
    deps
  ).promise
}

function lookupSource(
  worktreeId: string,
  incarnation: string,
  attempt: FirstWorkAttempt,
  deps: FirstWorkRetryDeps
): FirstWorkContextSource {
  return async () => {
    const controller = new AbortController()
    const deadlineAt = Date.now() + FIRST_WORK_RETRY_LOOKUP_DEADLINE_MS
    let timer: ReturnType<typeof setTimeout> | undefined
    const expired = new Promise<FirstWorkContextResolution>((resolve) => {
      timer = setTimeout(() => {
        attempt.expireLookup()
        controller.abort()
        resolve(unreadable)
      }, FIRST_WORK_RETRY_LOOKUP_DEADLINE_MS)
    })
    try {
      return await Promise.race([
        lookupContext(worktreeId, incarnation, attempt, controller.signal, deadlineAt, deps),
        expired
      ])
    } finally {
      clearTimeout(timer)
    }
  }
}

async function lookupContext(
  worktreeId: string,
  incarnation: string,
  attempt: FirstWorkAttempt,
  signal: AbortSignal,
  deadlineAt: number,
  deps: FirstWorkRetryDeps
): Promise<FirstWorkContextResolution> {
  const createdAt = deps.getWorkspaceCreatedAt(worktreeId)
  if (createdAt !== undefined) {
    const native = await leaseNativeFirstMessageRead(
      incarnation,
      () => attempt.isCurrent(),
      (stillWanted) => readNativeFirstMessage(deps.nativeReads(worktreeId), createdAt, stillWanted)
    )
    if (native.kind === 'unreadable') {
      return unreadable
    }
    if (native.kind === 'found') {
      return { kind: 'context', context: { firstPrompt: native.prompt } }
    }
    // 'none' and 'incomplete' (scan bound reached) both name from the workspace's changes.
  }
  const worktreePath = splitWorktreeIdForFilesystem(worktreeId)?.worktreePath
  if (parseWorkspaceKey(worktreeId)?.type === 'folder' || !worktreePath) {
    return {
      kind: 'outcome',
      outcome: { kind: 'ineligible', reason: 'first-message-unavailable' }
    }
  }
  const changes = await readBranchChangesForNaming({
    cwd: worktreePath,
    baseRef: deps.getBaseRef(worktreeId),
    signal,
    deadlineAt,
    runGit: deps.runGit
  })
  if (changes.kind === 'unreadable') {
    return unreadable
  }
  if (changes.kind === 'nothing-yet') {
    return { kind: 'outcome', outcome: { kind: 'nothing-yet' } }
  }
  return { kind: 'context', context: branchNameContextFromChanges(changes.changes) }
}

/** Cheap guards only; no history is read until the click. */
export async function getFirstWorkRetryAvailability(
  worktreeId: string,
  executionHostId: string | undefined,
  deps: FirstWorkBranchRenameDeps
): Promise<BranchAutoRenameRetryAvailability> {
  const unavailable = { available: false, runningAttemptId: null }
  if ((executionHostId ?? LOCAL_EXECUTION_HOST_ID) !== LOCAL_EXECUTION_HOST_ID) {
    return unavailable
  }
  const incarnation = deps.readIncarnation(worktreeId)
  if (!incarnation) {
    return unavailable
  }
  const running = runningFirstWorkAttempt(worktreeId, incarnation)
  if (running) {
    return { available: true, runningAttemptId: running.attemptId }
  }
  if (!deps.getSettings().autoRenameBranchFromWork) {
    return unavailable
  }
  if (parseWorkspaceKey(worktreeId)?.type === 'folder') {
    const pending =
      deps.isPendingFirstAgentMessageRename?.(worktreeId) === true &&
      !!deps.getFolderWorkspacePath?.(worktreeId)
    return pending ? { available: true, runningAttemptId: null } : unavailable
  }
  const repo = deps.getRepo(getRepoIdFromWorktreeId(worktreeId))
  const worktreePath = splitWorktreeIdForFilesystem(worktreeId)?.worktreePath
  if (
    !repo ||
    !worktreePath ||
    isFolderRepo(repo) ||
    resolveGitRouteForHost(getRepoExecutionHostId(repo)).kind !== 'local' ||
    !deps.canRenameOrcaCreatedBranch(worktreeId)
  ) {
    return unavailable
  }
  // A background probe must never boot a stopped WSL distro; a refusal leaves retry available.
  const exec: GitExec = (args) =>
    guardWslUncPathAccess(worktreePath, () => gitExecFileAsync(args, { cwd: worktreePath }))
  try {
    // Not getGitCurrentBranchName: it swallows errors, and a failed read must reach the catch.
    // Prints refs/heads/<branch> even beside a same-named tag, and "HEAD" when detached.
    const head = (await exec(['rev-parse', '--symbolic-full-name', 'HEAD'])).stdout.trim()
    const leaf = head.startsWith('refs/heads/') ? head.slice(head.lastIndexOf('/') + 1) : ''
    if (!isAutoGeneratedCreatureBranchName(leaf)) {
      return unavailable
    }
    const upstream = await probeBranchUpstream(exec)
    return upstream.outcome === 'has-upstream'
      ? unavailable
      : { available: true, runningAttemptId: null }
  } catch {
    // A transient Git failure here must not hide the control; the attempt reports it.
    return { available: true, runningAttemptId: null }
  }
}
