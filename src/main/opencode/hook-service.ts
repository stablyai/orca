    'function clearLifecycleRetry() {',
    '  if (lifecycleRetryTimer) clearTimeout(lifecycleRetryTimer);',
    '  lifecycleRetryTimer = null;',
    '  lifecycleRetryAttempt = 0;',
    '  lifecycleRetryTargetKey = null;',
    '  lifecycleRetryPreferredSessionID = null;',
    '}',
    'function setLifecycleRetryTarget(targetKey, preferredSessionID) {',
    '  if (lifecycleRetryTargetKey === targetKey) {',
    '    lifecycleRetryPreferredSessionID = preferredSessionID;',
    '    return false;',
    '  }',
    '  clearLifecycleRetry();',
    '  lifecycleRetryTargetKey = targetKey;',
    '  lifecycleRetryPreferredSessionID = preferredSessionID;',
    '  return true;',
    '}',
    'function scheduleLifecycleRetry() {',
    '  if (',
    '    lifecycleRetryTimer ||',
    '    lifecycleRetryTargetKey === null ||',
    '    activeFactoryIDs.size === 0',
    '  ) return;',
    '  const targetKey = lifecycleRetryTargetKey;',
    '  const preferredSessionID = lifecycleRetryPreferredSessionID;',
    '  // Why: a surviving agent may outlast an Orca restart. Ramp quickly, then',
    '  // keep one low-frequency unrefd probe alive until this state is superseded.',
    '  const delay = Math.min(',
    '    LIFECYCLE_RETRY_MS * Math.pow(2, Math.min(lifecycleRetryAttempt, 30)),',
    '    LIFECYCLE_RETRY_MAX_MS',
    '  );',
    '  lifecycleRetryAttempt = Math.min(lifecycleRetryAttempt + 1, 31);',
    '  lifecycleRetryTimer = setTimeout(() => {',
    '    lifecycleRetryTimer = null;',
    '    void enqueueCoordinatorWork(async () => {',
    '      // A newer busy/waiting/error target invalidates this queued retry.',
    '      if (lifecycleRetryTargetKey !== targetKey || activeFactoryIDs.size === 0) return;',
    '      await publishAggregateStatus(preferredSessionID, targetKey);',
    '    });',
    '  }, delay);',
    '  if (lifecycleRetryTimer.unref) lifecycleRetryTimer.unref();',
    '}',
