    'function latestTerminalOutcome() {',
    '  let latestError = null;',
    '  let latestAborted = null;',
    '  for (const outcome of terminalOutcomeByRootSessionID.values()) {',
    '    if (outcome.type === "error") latestError = outcome;',
    '    else latestAborted = outcome;',
    '  }',
    '  return latestError || latestAborted;',
