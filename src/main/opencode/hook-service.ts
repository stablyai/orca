    'function retireDeliveredTerminalOutcomes() {',
    '  if (lastDeliveredTerminalOutcomeID === 0) return;',
    '  for (const [sessionID, outcome] of terminalOutcomeByRootSessionID) {',
    '    if (outcome.id <= lastDeliveredTerminalOutcomeID) {',
