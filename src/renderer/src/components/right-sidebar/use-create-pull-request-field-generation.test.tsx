// @vitest-environment happy-dom
import { act, cleanup, renderHook } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import type * as RuntimeGeneration from '@/runtime/runtime-git-generation-client'
import { getDefaultSettings } from '../../../../shared/constants'
import { resolveSourceControlAiForOperation } from '../../../../shared/source-control-ai'
import {
  DEFAULT_SOURCE_CONTROL_AI_PR_CREATION_DEFAULTS,
  getDefaultSourceControlAiSettings
} from '../../../../shared/source-control-ai-settings'
import { useCreatePullRequestFieldGeneration } from './use-create-pull-request-field-generation'

const runtime = vi.hoisted(() => ({
  generate: vi.fn<typeof RuntimeGeneration.generateRuntimePullRequestFields>(),
  cancel: vi.fn<typeof RuntimeGeneration.cancelRuntimeGeneratePullRequestFields>()
}))
vi.mock('@/runtime/runtime-git-generation-client', () => ({
  generateRuntimePullRequestFields: runtime.generate,
  cancelRuntimeGeneratePullRequestFields: runtime.cancel
}))

function input(): Parameters<typeof useCreatePullRequestFieldGeneration>[0] {
  const settings = {
    ...getDefaultSettings('/fixture'),
    sourceControlAi: { ...getDefaultSourceControlAiSettings(), agentId: 'codex' as const }
  }
  return {
    open: true,
    submitting: false,
    resolvedPullRequestAi: resolveSourceControlAiForOperation({
      settings,
      operation: 'pullRequest'
    }),
    base: 'main',
    title: '',
    body: '',
    draft: false,
    worktreeId: null,
    worktreePath: '/folder',
    settings,
    target: { kind: 'local' },
    eligibility: null,
    resolvedPrDefaults: DEFAULT_SOURCE_CONTROL_AI_PR_CREATION_DEFAULTS,
    generation: undefined,
    applyGeneratedFields: (fields) => fields,
    generating: false,
    generateError: null,
    setGenerating: vi.fn(),
    setGenerateError: vi.fn(),
    initializedFromEligibilityRef: { current: null },
    autoGeneratedForKeyRef: { current: null },
    generateInFlightRef: { current: false },
    generationRequestIdRef: { current: 0 },
    generationSeedRef: { current: null },
    fieldRevisionsRef: { current: { base: 0, title: 0, body: 0, draft: 0 } }
  }
}

afterEach(() => {
  cleanup()
  runtime.generate.mockReset()
  runtime.cancel.mockReset().mockResolvedValue(undefined)
})

it('local dialog Stop retains the generated request identity and suppresses later dispatch', async () => {
  let answer: (
    result: Awaited<ReturnType<typeof RuntimeGeneration.generateRuntimePullRequestFields>>
  ) => void = () => {}
  runtime.generate.mockImplementation(
    () =>
      new Promise((resolve) => {
        answer = resolve
      })
  )
  const model = input()
  const { result } = renderHook(() => useCreatePullRequestFieldGeneration(model))
  const request = result.current.handleGenerate()
  const context = model.generationSeedRef.current?.context
  expect(context?.generationId).toMatch(/^[0-9a-f-]{36}$/)
  const isCanceled = runtime.generate.mock.calls[0][3]
  expect(isCanceled?.()).toBe(false)
  act(() => result.current.handleCancelGenerate())
  expect(isCanceled?.()).toBe(true)
  expect(runtime.cancel).toHaveBeenCalledWith(context)
  answer({ success: false, error: 'Generation canceled.', canceled: true })
  await expect(request).resolves.toEqual({ result: null })
})

it('local hook unmount does not flip explicit Stop state or cancel the owner', async () => {
  let answer: (
    result: Awaited<ReturnType<typeof RuntimeGeneration.generateRuntimePullRequestFields>>
  ) => void = () => {}
  runtime.generate.mockImplementation(
    () =>
      new Promise((resolve) => {
        answer = resolve
      })
  )
  const model = input()
  const { result, unmount } = renderHook(() => useCreatePullRequestFieldGeneration(model))
  const request = result.current.handleGenerate()
  unmount()
  expect(runtime.generate.mock.calls[0][3]?.()).toBe(false)
  expect(runtime.cancel).not.toHaveBeenCalled()
  answer({ success: true, fields: { base: 'main', title: 'Feature', body: '', draft: false } })
  await expect(request).resolves.toMatchObject({ result: { title: 'Feature' } })
})

it('coalesces local dialog generation calls before React commits the busy state', async () => {
  let answer: (
    result: Awaited<ReturnType<typeof RuntimeGeneration.generateRuntimePullRequestFields>>
  ) => void = () => {}
  runtime.generate.mockImplementation(
    () =>
      new Promise((resolve) => {
        answer = resolve
      })
  )
  const model = input()
  const { result } = renderHook(() => useCreatePullRequestFieldGeneration(model))
  const first = result.current.handleGenerate()
  await expect(result.current.handleGenerate()).resolves.toBeUndefined()
  expect(runtime.generate).toHaveBeenCalledTimes(1)
  answer({ success: true, fields: { base: 'main', title: 'Feature', body: '', draft: false } })
  await expect(first).resolves.toMatchObject({ result: { title: 'Feature' } })
  expect(model.generateInFlightRef.current).toBe(false)
})
