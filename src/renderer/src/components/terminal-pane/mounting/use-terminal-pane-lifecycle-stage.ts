import { useIssueCommandSplitSettlement } from '../layout/split/use-issue-command-split-settlement'
import { useTerminalPaneStoreActions } from '../controller/use-terminal-pane-store-actions'
import { useTerminalPaneLifecycle } from '../controller/use-terminal-pane-lifecycle'
import type { TerminalPaneCloseController } from '../layout/close/use-terminal-pane-close-actions'

export function useTerminalPaneLifecycleStage(controller: TerminalPaneCloseController) {
  const {
    consumeTabIssueCommandSplit,
    clearExitedPanePtyLayoutBinding,
    clearExitedPanePtyLayoutBindingForLeaf,
    clearRuntimePaneTitle,
    clearTabPtyId,
    clearedScrollbackLeafIdsRef,
    containerRef,
    cwd,
    dispatchNotification,
    effectiveMacOptionAsAlt,
    detachPaneToNewTab,
    handleExternalPaneDrop,
    initialLayoutRef,
    isActive,
    isActiveRef,
    isRendererVisible,
    isVisibleRef,
    issueCommandSplit,
    macOptionAsAltRef,
    managerRef,
    markTerminalBell,
    onAgentExitedRef,
    onPtyErrorClearedRef,
    onPtyErrorRef,
    onPtyExitRef,
    onPtyRecoveryStateRef,
    paneCwdRef,
    paneKittyKeyboardModesRef,
    paneLastThemeModeRef,
    paneMode2031Ref,
    panePtyBindingsRef,
    paneTitlesRef,
    paneTransportsRef,
    persistLayoutSnapshot,
    refreshMobileOverlays,
    replayingPanesRef,
    requestOpenLinksInAppPreference,
    requestTerminalLinkAction,
    settleTabStartupCommand,
    resolveExternalPaneDropTarget,
    setCacheTimerStartedAt,
    setExpandedPane,
    setPaneCount,
    setPaneLayoutRevision,
    setPaneTitles,
    setRenamingPaneId,
    setRuntimePaneTitle,
    showPaneTitle,
    setTabCanExpandPane,
    setTabPaneExpanded,
    settings,
    settingsRef,
    showRestoredSessionBanner,
    startup,
    syncExpandedLayout,
    syncPanePtyLayoutBinding,
    syncPanePtyLayoutBindingForLeaf,
    systemPrefersDark,
    tabId,
    updateTabPtyId,
    updateTabTitle,
    worktreeId,
    expandedStyleSnapshotRef,
    getTabWideAgentHintLeafIdRef,
    handlePaneProcessDied
  } = controller
  const { consumeSuppressedPtyExit, isPtyShutdownPending } = useTerminalPaneStoreActions()

  const mount = useTerminalPaneLifecycle({
    tabId,
    worktreeId,
    cwd,
    startup,
    issueCommandSplit,
    isActive,
    isVisible: isRendererVisible,
    systemPrefersDark,
    settings,
    settingsRef,
    requestOpenLinksInAppPreference,
    requestTerminalLinkAction,
    effectiveMacOptionAsAlt,
    effectiveMacOptionAsAltRef: macOptionAsAltRef,
    initialLayoutRef,
    clearedScrollbackLeafIdsRef,
    managerRef,
    getTabWideAgentHintLeafId: () => getTabWideAgentHintLeafIdRef.current(),
    containerRef,
    expandedStyleSnapshotRef,
    paneTransportsRef,
    paneCwdRef,
    paneMode2031Ref,
    paneKittyKeyboardModesRef,
    paneLastThemeModeRef,
    panePtyBindingsRef,
    replayingPanesRef,
    isActiveRef,
    isVisibleRef,
    onPtyExitRef,
    onAgentExitedRef,
    onPtyErrorRef,
    onPtyErrorClearedRef,
    onPaneProcessDied: handlePaneProcessDied,
    onPtyRecoveryStateRef,
    clearTabPtyId,
    consumeSuppressedPtyExit,
    isPtyShutdownPending,
    updateTabTitle,
    setRuntimePaneTitle,
    clearRuntimePaneTitle,
    updateTabPtyId,
    markTerminalBell,
    onShowSessionRestoredBanner: showRestoredSessionBanner,
    dispatchNotification,
    setCacheTimerStartedAt,
    syncPanePtyLayoutBinding,
    syncPanePtyLayoutBindingForLeaf,
    clearExitedPanePtyLayoutBinding,
    clearExitedPanePtyLayoutBindingForLeaf,
    onStartupBound: settleTabStartupCommand,
    refreshMobileOverlays,
    setTabPaneExpanded,
    setTabCanExpandPane,
    setExpandedPane,
    syncExpandedLayout,
    persistLayoutSnapshot,
    showPaneTitle,
    setPaneTitles,
    paneTitlesRef,
    setRenamingPaneId,
    setPaneCount,
    setPaneLayoutRevision,
    resolveExternalPaneDropTarget,
    onExternalPaneDrop: handleExternalPaneDrop,
    detachPaneToNewTab
  })
  useIssueCommandSplitSettlement({
    consumeTabIssueCommandSplit,
    issueCommandSplit,
    tabId,
    terminalManager: mount.manager
  })
  return { terminalMountPhase: mount.phase, terminalManager: mount.manager }
}

export type TerminalPaneMountedController = TerminalPaneCloseController &
  ReturnType<typeof useTerminalPaneLifecycleStage>
