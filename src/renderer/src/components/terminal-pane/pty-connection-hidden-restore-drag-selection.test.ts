function createDeps(overrides: Record<string, unknown> = {}) {
  return buildPaneConnectionDeps(() => mockStoreState, overrides)
}

describe('connectPanePty', () => {
  beforeEach(async () => {
    vi.resetModules()
    vi.clearAllMocks()
    transportFactoryQueue = []
    createdTransportOptions = []
    storeSubscribers = []
    mockStoreState = createInitialStoreState(() => mockStoreState)
    await installTerminalTestGlobals()
  })

  afterEach(async () => {
    await restoreTerminalTestGlobals()
  })

  it('parks a hidden-output snapshot replay until a held drag selection ends', async () => {
    const { connectPanePty } = await import('./pty-connection')
    const transport = createMockTransport('remote:env-1@@terminal-1')
    const capturedDataCallback: {
      current: ((data: string, meta?: { seq?: number; rawLength?: number }) => void) | null
    } = { current: null }
    const hidden = 'x'.repeat(2 * 1024 * 1024 + 1)
    const live = 'visible remote output\r\n'
    transport.serializeBuffer = vi.fn().mockResolvedValue({
      data: 'remote snapshot with hidden remote output\r\n',
      cols: 120,
      rows: 40,
      seq: hidden.length + live.length,
      source: 'headless'
    })
    transport.connect.mockImplementation(async ({ callbacks }: { callbacks: ConnectCallbacks }) => {
      capturedDataCallback.current = callbacks.onData ?? null
      return 'remote:env-1@@terminal-1'
    })
    transportFactoryQueue.push(transport)

    const pane = createPane(1)
    // Why: the selection guard listens on the real terminal element; the default fixture element is inert.
    const terminalElement = new EventTarget()
    const ownerDocument = new EventTarget()
    Object.assign(ownerDocument, { defaultView: new EventTarget() })
    Object.assign(terminalElement, { ownerDocument })
    pane.terminal.element = terminalElement
    const deps = createDeps({ isVisibleRef: { current: false } })
    const disposable = connectPanePty(pane as never, createManager(1) as never, deps as never)
    await flushAsyncTicks(6)

    capturedDataCallback.current?.(hidden, { seq: hidden.length, rawLength: hidden.length })
    // The click that brings the window back starts a drag selection before the replay lands.
    const mouseDown = new Event('mousedown')
    Object.defineProperty(mouseDown, 'button', { value: 0 })
    terminalElement.dispatchEvent(mouseDown)
    ;(deps.isVisibleRef as { current: boolean }).current = true
    capturedDataCallback.current?.(live, {
      seq: hidden.length + live.length,
      rawLength: live.length
    })
    await flushAsyncTicks(20)

    const snapshotWritten = (): boolean =>
      pane.terminal.write.mock.calls.some(([data]) =>
        String(data).includes('remote snapshot with hidden remote output')
      )
    expect(transport.serializeBuffer).toHaveBeenCalledTimes(1)
    expect(snapshotWritten()).toBe(false)

    // A new drag that starts before the queued replay task runs must park it again.
    ownerDocument.dispatchEvent(new Event('mouseup'))
    terminalElement.dispatchEvent(mouseDown)
    await flushAsyncTicks(20)
    expect(snapshotWritten()).toBe(false)

    ownerDocument.dispatchEvent(new Event('mouseup'))
    await flushAsyncTicks(20)

    expect(snapshotWritten()).toBe(true)
    expect(transport.serializeBuffer).toHaveBeenCalledTimes(1)
    disposable.dispose()
  })
})
