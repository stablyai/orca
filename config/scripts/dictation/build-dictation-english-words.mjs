// Regenerates src/shared/dictation-english-words.ts, the common-word filter dictation's near-miss matching
// checks before spelling a word as a dictionary term. Run: node config/scripts/dictation/build-dictation-english-words.mjs
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { wordFilterSlots } from '../../../src/shared/dictation-word-filter.ts'

const SOURCES = {
  scowl: [
    'https://downloads.sourceforge.net/project/wordlist/SCOWL/2020.12.07/scowl-2020.12.07.tar.gz',
    '5587667caa20c4891390c2d42dbb4d5c4c3f41bee77af1457ece3ba23fb859cc'
  ],
  femaleFirst: [
    'https://www2.census.gov/topics/genealogy/1990surnames/dist.female.first',
    'bd2f310fc4e5d5e5ea122c9d4342c9821145823118eb20db1647f305ec77b358'
  ],
  maleFirst: [
    'https://www2.census.gov/topics/genealogy/1990surnames/dist.male.first',
    '0a5078ef6effe3b483d15b0f7f95047662126c9bfb624ecd5e5b978fc0f2470b'
  ],
  last: [
    'https://www2.census.gov/topics/genealogy/1990surnames/dist.all.last',
    'b0e2b3743ccbad641ca48b344c24cdebcd1d9a1f76dc6dbf05986f2919f0b4e1'
  ]
}
// SCOWL sizes up to 60: everyday words plus the rarer ones ("bezel", "aslant") a term could sound like.
const SCOWL_MAX_SIZE = 60
const LAST_NAMES = 1000
const FALSE_POSITIVE_RATE = 0.02
// Matching never looks up words shorter than this.
const MIN_WORD_LENGTH = 3
const OUT = 'src/shared/dictation-english-words.ts'

async function download([url, sha256]) {
  const response = await fetch(url)
  if (!response.ok) {
    throw new Error(`${url}: HTTP ${response.status}`)
  }
  const bytes = Buffer.from(await response.arrayBuffer())
  const actual = createHash('sha256').update(bytes).digest('hex')
  if (actual !== sha256) {
    throw new Error(`${url}: sha256 ${actual}, expected ${sha256}`)
  }
  return bytes
}

const work = mkdtempSync(join(tmpdir(), 'dictation-english-words-'))
try {
  const words = new Set()
  // Contractions add their stems ("doesn" of "doesn't"), since dictated text splits words at apostrophes.
  const add = (entry) => {
    for (const part of entry.split("'")) {
      if (/^[A-Za-z]+$/.test(part) && part.length >= MIN_WORD_LENGTH) {
        words.add(part.toLowerCase())
      }
    }
  }
  writeFileSync(join(work, 'scowl.tar.gz'), await download(SOURCES.scowl))
  execFileSync('tar', ['-xzf', 'scowl.tar.gz'], { cwd: work })
  const final = join(work, 'scowl-2020.12.07', 'final')
  for (const file of readdirSync(final)) {
    const list =
      /^(?:english|american|british|canadian|australian)-(?:words|upper|contractions)\.(\d+)$/.exec(
        file
      )
    if (list && Number(list[1]) <= SCOWL_MAX_SIZE) {
      readFileSync(join(final, file), 'latin1').split('\n').forEach(add)
    }
  }
  const names = async (source, limit) =>
    (await download(source))
      .toString('latin1')
      .trim()
      .split('\n')
      .slice(0, limit)
      .map((line) => line.split(/\s+/)[0])
  for (const name of [
    ...(await names(SOURCES.femaleFirst)),
    ...(await names(SOURCES.maleFirst)),
    ...(await names(SOURCES.last, LAST_NAMES))
  ]) {
    add(name)
  }

  const bits = Math.ceil((-words.size * Math.log(FALSE_POSITIVE_RATE)) / Math.LN2 ** 2 / 8) * 8
  const hashes = Math.round((bits / words.size) * Math.LN2)
  const bytes = new Uint8Array(bits / 8)
  for (const word of words) {
    for (const slot of wordFilterSlots(word, bits, hashes)) {
      bytes[slot >>> 3] |= 1 << (slot & 7)
    }
  }
  // The whole SCOWL notice (Atkinson, WordNet, VarCon, Ispell and the rest) rides in every bundle that keeps legal comments.
  const license = readFileSync('resources/licenses/scowl/Copyright', 'utf8').trimEnd().split('\n')
  const notice = [
    `A filter of ${words.size} common English words and names: SCOWL 2020.12.07 words, capitalized words and`,
    `contractions up to size ${SCOWL_MAX_SIZE} (english, american, british, canadian, australian), a-z only, lowercased,`,
    `plus the 1990 US census first names and ${LAST_NAMES} most common last names (public domain). Generated by`,
    'config/scripts/dictation/build-dictation-english-words.mjs from these SCOWL notices:',
    '',
    ...license.map((line) => line.replaceAll('*/', '* /'))
  ]
  writeFileSync(
    OUT,
    `/*! @license\n${notice.map((line) => ` * ${line}`.trimEnd()).join('\n')}\n */\n` +
      `import type { WordFilter } from './dictation-word-filter'\n\n` +
      `export const COMMON_ENGLISH_WORDS: WordFilter = {\n  bits: ${bits},\n  hashes: ${hashes},\n` +
      `  base64:\n    '${Buffer.from(bytes).toString('base64')}'\n}\n`
  )
  console.log(`${OUT}: ${words.size} words, ${bits} bits, ${hashes} hashes`)
} finally {
  rmSync(work, { recursive: true, force: true })
}
