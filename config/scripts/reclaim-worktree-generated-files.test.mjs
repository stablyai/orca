it('skips symlinked targets and package ancestors, and nested repositories', async () => {
  const f = await fixture()
  const external = join(f.root, 'external')
  const outside = await generated(external)
  await writeFile(join(external, 'package.json'), '{}')
  await symlink(external, join(f.sibling, 'node_modules'), 'junction')
  await rm(join(f.sibling, 'native', 'addon'), { recursive: true })
  await symlink(external, join(f.sibling, 'native', 'addon'), 'junction')
  const nested = await generated(f.sibling, 'mobile/node_modules')
  await writeFile(join(f.sibling, 'mobile', '.git'), 'gitdir: elsewhere')
  const preview = await reclaimWorktreeGeneratedFiles({ repoRoot: f.repoRoot, report: () => {} })
  expect(preview.entries).toBe(0)
  expect(await readFile(outside, 'utf8')).toBe('generated bytes')
  expect(await readFile(nested, 'utf8')).toBe('generated bytes')
})

it.each(['directory', 'file'])(
  'preserves uncommitted source in a nested repository with a .git %s beneath output',
  async (kind) => {
    const f = await fixture()
    const file = await generated(f.sibling, 'out')
    const nested = join(dirname(file), 'local-checkout')
    await mkdir(nested)
    await (kind === 'directory'
      ? f.git('-C', nested, 'init', '--quiet')
      : writeFile(join(nested, '.git'), 'gitdir: elsewhere'))
    const source = join(nested, 'source.js')
    await writeFile(source, 'uncommitted source')
    await utimes(dirname(file), new Date(0), new Date(0))
    for (const apply of [false, true]) {
      const result = await reclaimWorktreeGeneratedFiles({
        repoRoot: f.repoRoot,
        apply,
        report: () => {}
      })
      expect(result.entries).toBe(0)
      expect(result.protected).toBe(1)
      expect(await readFile(source, 'utf8')).toBe('uncommitted source')
      expect(await readFile(file, 'utf8')).toBe('generated bytes')
    }
  }
)

it('preserves bare repositories and their refs beneath ignored output', async () => {
  const f = await fixture()
  const file = await generated(f.sibling, 'out')
  const nested = join(dirname(file), 'saved.git')
  await f.git('clone', '--quiet', '--bare', f.repoRoot, nested)
  const head = await readFile(join(nested, 'HEAD'), 'utf8')
  await utimes(dirname(file), new Date(0), new Date(0))
  const result = await reclaimWorktreeGeneratedFiles({
    repoRoot: f.repoRoot,
    apply: true,
    report: () => {}
  })
  expect(result.entries).toBe(0)
  expect(result.protected).toBe(1)
  expect(await readFile(join(nested, 'HEAD'), 'utf8')).toBe(head)
  expect((await lstat(join(nested, 'objects'))).isDirectory()).toBe(true)
})

