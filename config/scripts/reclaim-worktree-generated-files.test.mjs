it('retains a replacement directory introduced while the final Git check is running', async () => {
  const f = await fixture()
  const file = await generated(f.sibling)
  const target = dirname(file)
  const saved = join(f.sibling, 'saved-original')
  const execute = processHost.runProcess
  let checks = 0
  vi.spyOn(processHost, 'runProcess').mockImplementation(async (spec) => {
    const result = await execute(spec)
    if (
      spec.args.includes('check-ignore') &&
      spec.args.at(-1) === 'node_modules/' &&
      ++checks === 2
    ) {
      await rename(target, saved)
      await generated(f.sibling)
    }
    return result
  })
  const result = await reclaimWorktreeGeneratedFiles({
    repoRoot: f.repoRoot,
    apply: true,
    report: () => {}
  })
  expect(checks).toBe(2)
  expect(result.protected).toBe(1)
  expect(await readFile(file, 'utf8')).toBe('generated bytes')
  expect(await readFile(join(saved, 'generated.txt'), 'utf8')).toBe('generated bytes')
})

it('supports a retention override and rejects invalid ages', async () => {
  const f = await fixture()
  const file = await generated(f.sibling, 'mobile/node_modules', 2)
  await reclaimWorktreeGeneratedFiles({
    repoRoot: f.repoRoot,
    apply: true,
    generatedMinAgeDays: 1,
    report: () => {}
  })
  await expect(lstat(file)).rejects.toMatchObject({ code: 'ENOENT' })
  await expect(
    reclaimWorktreeGeneratedFiles({ repoRoot: f.repoRoot, generatedMinAgeDays: Number.NaN })
  ).rejects.toThrow('--generated-min-age-days')
})

it.skipIf(process.platform === 'win32' || process.getuid?.() === 0)(
  'reclaims read-only generated directories without chmodding hardlinked package files',
  async () => {
    const f = await fixture()
    const shared = join(f.root, 'shared-package.js')
    await writeFile(shared, 'shared package', { mode: 0o444 })
    const originalMode = (await lstat(shared)).mode & 0o777
    const file = await generated(f.sibling)
    await link(shared, join(dirname(file), 'package.js'))
    await utimes(dirname(file), new Date(0), new Date(0))
    await chmod(dirname(file), 0o555)
    await reclaimWorktreeGeneratedFiles({
      repoRoot: f.repoRoot,
      apply: true,
      report: () => {}
    })
    await expect(lstat(file)).rejects.toMatchObject({ code: 'ENOENT' })
    expect(await readFile(shared, 'utf8')).toBe('shared package')
    expect((await lstat(shared)).mode & 0o777).toBe(originalMode)
  }
)

it.each(['manual', 'automatic'])(
  'includes generated cleanup in %s CLI preview and apply',
  async (mode) => {
    const f = await fixture()
    const protectedFile = await generated(f.repoRoot)
    const file = await generated(f.sibling, 'mobile/node_modules')
    const store = join(f.root, 'global-pnpm-store')
    await mkdir(store)
    const shared = join(store, 'package.js')
    await writeFile(shared, 'shared package')
    await link(shared, join(dirname(file), 'package.js'))
    await symlink(store, join(dirname(file), 'shared-package'), 'junction')
    await utimes(dirname(file), new Date(0), new Date(0))
    const run = (args) =>
      runProcess({
        program: process.env.ORCA_TEST_NODE_EXECUTABLE ?? process.execPath,
        args: [
          resolve(import.meta.dirname, 'reclaim-worktree-space.mjs'),
          '--repo',
          f.repoRoot,
          ...(mode === 'automatic' ? ['--automatic'] : []),
          ...args
        ],
        cwd: tmpdir(),
        env: { ...process.env, ORCA_BACKGROUND_LAUNCH: '1' },
        timeoutMs: 30_000,
        terminationBarrier: true
      })
    const preview = await run([])
    expect(preview.code, preview.stderr).toBe(0)
    expect(preview.stdout).toContain('would remove generated directory')
    expect(await readFile(file, 'utf8')).toBe('generated bytes')
    const applied = await run(['--apply'])
    expect(applied.code, applied.stderr).toBe(0)
    await expect(lstat(file)).rejects.toMatchObject({ code: 'ENOENT' })
    expect(await readFile(protectedFile, 'utf8')).toBe('generated bytes')
    expect(await readFile(shared, 'utf8')).toBe('shared package')
  }
)
