// Writes src/shared/theme/theme-built-in-values.generated.ts: Orca's built-in token values per mode,
// read from main.css, so the contrast gate can run without a browser (CLI, host, validate).
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { createRequire } from 'node:module'
import { pathToFileURL } from 'node:url'
import * as esbuild from 'esbuild'
import { resolveOxcCliInvocation } from '../tool-invocation/oxc-cli-invocation.mjs'

const REPO_ROOT = path.resolve(import.meta.dirname, '../../..')
const MAIN_CSS = path.join(REPO_ROOT, 'src', 'renderer', 'src', 'assets', 'main.css')
const OUTPUT_PATH = path.join(
  REPO_ROOT,
  'src',
  'shared',
  'theme',
  'theme-built-in-values.generated.ts'
)

function scratchDir(prefix) {
  const root = path.join(REPO_ROOT, 'out')
  mkdirSync(root, { recursive: true })
  return mkdtempSync(path.join(root, prefix))
}

/** main.css with its local @imports inlined in place, as the bundled stylesheet orders them. */
function stylesheet(file, seen = new Set()) {
  if (seen.has(file)) {
    return ''
  }
  seen.add(file)
  return readFileSync(file, 'utf8').replace(/@import\s+['"](\.[^'"]+)['"]\s*;/g, (_all, target) =>
    stylesheet(path.resolve(path.dirname(file), target), seen)
  )
}

/** Tailwind's default theme variables (`--color-blue-300`, …), which main.css tokens reference and
 *  Tailwind emits on :root. */
function tailwindThemeRoot() {
  const require = createRequire(path.join(REPO_ROOT, 'src', 'renderer', 'package.json'))
  const theme = readFileSync(require.resolve('tailwindcss/theme.css'), 'utf8')
  const block = /@theme default \{([\s\S]*?)\n\}/.exec(theme)
  return block ? `:root {${block[1]}\n}\n` : ''
}

async function loadModules() {
  const dir = scratchDir('theme-built-in-values-')
  try {
    const outfile = path.join(dir, 'entry.mjs')
    await esbuild.build({
      stdin: {
        contents: [
          `export { themeBuiltInValuesFromCss } from './src/shared/theme/theme-built-in-css'`,
          `export { PLUGIN_APP_THEME_TOKENS } from './src/shared/plugins/artifacts/plugin-theme-artifact'`
        ].join('\n'),
        resolveDir: REPO_ROOT,
        loader: 'ts'
      },
      bundle: true,
      platform: 'node',
      format: 'esm',
      outfile,
      logLevel: 'silent'
    })
    return await import(pathToFileURL(outfile).href)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

function formatted(source) {
  const dir = scratchDir('theme-built-in-values-fmt-')
  try {
    const file = path.join(dir, 'theme-built-in-values.generated.ts')
    writeFileSync(file, source)
    const { command, prefixArgs } = resolveOxcCliInvocation('oxfmt', 'oxfmt', REPO_ROOT)
    execFileSync(command, [...prefixArgs, '--write', file], { stdio: 'ignore', windowsHide: true })
    return readFileSync(file, 'utf8')
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

async function main() {
  const check = process.argv.includes('--check')
  const { themeBuiltInValuesFromCss, PLUGIN_APP_THEME_TOKENS } = await loadModules()
  const values = themeBuiltInValuesFromCss(
    tailwindThemeRoot() + stylesheet(MAIN_CSS),
    PLUGIN_APP_THEME_TOKENS
  )
  const generated = formatted(
    [
      '// Generated by config/scripts/theme/generate-theme-built-in-values.mjs from main.css. Do not edit.',
      '// Run `pnpm run generate:theme-built-in-values` after changing a public token in main.css.',
      '',
      `export const THEME_BUILT_IN_VALUES: Readonly<Record<'light' | 'dark', Readonly<Record<string, string>>>> = ${JSON.stringify(values, null, 2)}`,
      ''
    ].join('\n')
  )
  const current = existsSync(OUTPUT_PATH) ? readFileSync(OUTPUT_PATH, 'utf8') : null
  const relative = path.relative(REPO_ROOT, OUTPUT_PATH)
  if (generated === current) {
    if (!check) {
      console.log(`theme built-in values already up to date: ${relative}`)
    }
    return
  }
  if (check) {
    console.error(`${relative} is out of date. Run \`pnpm run generate:theme-built-in-values\`.`)
    process.exitCode = 1
    return
  }
  writeFileSync(OUTPUT_PATH, generated)
  console.log(`wrote ${relative}`)
}

await main()
