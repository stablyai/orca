function references(value) {
  if (!value || typeof value !== 'object') {
    return []
  }
  if (Array.isArray(value)) {
    return value.flatMap(references)
  }
  return [
    ...(value.$ref ? [value.$ref.split('/').at(-1)] : []),
    ...Object.values(value).flatMap(references)
  ]
}

const ordered = []
const visiting = new Set()
const visited = new Set()
function visit(name) {
  if (visited.has(name)) {
    return
  }
  if (visiting.has(name)) {
    throw new Error(`Recursive schema needs an explicit type: ${name}`)
  }
  if (!definitions[name]) {
    throw new Error(`Missing definition: ${name}`)
  }
  visiting.add(name)
  for (const dependency of references(definitions[name])) {
    visit(dependency)
  }
  visiting.delete(name)
  visited.add(name)
  ordered.push(name)
}
roots.forEach(visit)

function expression(value) {
  if (value === true) {
    return 'z.unknown()'
  }
  if (value === false) {
    return 'z.never()'
  }
  if (value.$ref) {
    return `${value.$ref.split('/').at(-1)}Schema`
  }
  if ('const' in value) {
    return `z.literal(${JSON.stringify(value.const)})`
  }
  const alternatives = value.oneOf ?? value.anyOf
  if (alternatives || value.allOf) {
    const combined = alternatives
      ? `z.union([${alternatives.map(expression).join(',')}])`
      : value.allOf.map(expression).reduce((left, right) => `z.intersection(${left},${right})`)
    const siblings = { ...value }
    delete siblings.oneOf
    delete siblings.anyOf
    delete siblings.allOf
    return siblings.type || siblings.properties
      ? `z.intersection(${expression(siblings)},${combined})`
      : combined
  }
  if (Array.isArray(value.type)) {
    return `z.union([${value.type.map((type) => expression({ ...value, type })).join(',')}])`
  }
  let result
  switch (value.type) {
    case 'string':
      result = 'z.string()'
      break
    case 'integer':
      result = 'z.number().int()'
      break
    case 'number':
      result = 'z.number()'
      break
    case 'boolean':
      result = 'z.boolean()'
      break
    case 'null':
      result = 'z.null()'
      break
    case 'array':
      result = `z.array(${expression(value.items ?? true)})`
      break
    case 'object': {
      const properties = Object.entries(value.properties ?? {}).map(
        ([key, property]) =>
          `${JSON.stringify(key)}:${expression(property)}${value.required?.includes(key) ? '' : '.optional()'}`
      )
      result = `z.${value.additionalProperties === false ? 'strictObject' : 'looseObject'}({${properties.join(',')}})`
      if (typeof value.additionalProperties === 'object') {
        result += `.catchall(${expression(value.additionalProperties)})`
      }
      break
    }
    default:
      if (
        Object.keys(value).some(
          (key) => !key.startsWith('x-') && !['description', 'title', 'default'].includes(key)
        )
      ) {
        throw new Error(`Unsupported schema: ${JSON.stringify(value)}`)
      }
      result = 'z.unknown()'
  }
  if (['integer', 'number'].includes(value.type) && typeof value.minimum === 'number') {
    result += `.min(${value.minimum})`
  }
  if (['integer', 'number'].includes(value.type) && typeof value.maximum === 'number') {
    result += `.max(${value.maximum})`
  }
  if (value.not) {
    result += `.refine(value=>!${expression(value.not)}.safeParse(value).success)`
  }
  return result
}

// Pack in dependency order so generated imports stay acyclic and each module stays small.
const groups = []
let group = []
let length = 0
for (const name of ordered) {
  const body = `export const ${name}Schema = ${expression(definitions[name])}\nexport type ${name} = z.infer<typeof ${name}Schema>\n`
  if (length + body.length > 4300 && group.length) {
    groups.push(group)
    group = []
    length = 0
  }
  group.push({ name, body })
  length += body.length
}
if (group.length) {
  groups.push(group)
}
const filenames = new Map()
for (const entries of groups) {
  const filename = entries[0].name.replace(
    /[A-Z]/g,
    (c, offset) => `${offset ? '-' : ''}${c.toLowerCase()}`
  )
  for (const { name } of entries) {
    filenames.set(name, `${filename}.gen.ts`)
  }
}

const generated = new Map()
for (const entries of groups) {
  const file = filenames.get(entries[0].name)
  const imports = new Map()
  for (const { body } of entries) {
    for (const dependency of [...body.matchAll(/\b(\w+)Schema\b/g)].map((match) => match[1])) {
      const source = filenames.get(dependency)
      if (source === file) {
        continue
      }
      if (!imports.has(source)) {
        imports.set(source, new Set())
      }
      imports.get(source).add(`${dependency}Schema`)
    }
  }
  generated.set(
    file,
    `${header}import { z } from 'zod'\n${[...imports]
      .map(
        ([source, names]) => `import { ${[...names].join(',')} } from './${source.slice(0, -3)}'\n`
      )
      .join('')}${entries.map((entry) => entry.body).join('\n')}`
  )
}
generated.set(
  'protocol.gen.ts',
  `${
    header +
    [...new Set(filenames.values())]
      .map((file) => `export * from './${file.slice(0, -3)}'`)
      .join('\n')
  }\n`
)
generated.set(
  'license.gen.ts',
  `${header}/*\n${license.trim()}\n*/\nexport const ACP_SCHEMA_RELEASE = '${release}'\nexport const ACP_LEGACY_MODEL_SCHEMA_RELEASE = '${legacyRelease}'\nexport const ACP_PROTOCOL_VERSION = 1\n`
)

// Use the repository formatter without spawning a platform-dependent executable shim.
const { format } = await import('oxfmt')
await mkdir(output, { recursive: true })
for (const [file, source] of generated) {
  const formatted = await format(file, source, {
    singleQuote: true,
    semi: false,
    printWidth: 100,
    trailingComma: 'none'
  })
  if (formatted.errors.length) {
    throw new Error(`Formatting failed for ${file}`)
  }
  const destination = resolve(output, file)
  if (check) {
    if ((await readFile(destination, 'utf8')) !== formatted.code) {
      throw new Error(`Stale generated file: ${file}`)
    }
  } else {
    await writeFile(destination, formatted.code)
  }
}
for (const file of await readdir(output)) {
  if (file.endsWith('.gen.ts') && !generated.has(file)) {
    if (check || !(await readFile(resolve(output, file), 'utf8')).startsWith(header)) {
      throw new Error(`Unexpected generated file: ${file}`)
    }
    await unlink(resolve(output, file))
  }
}
console.log(
  `${check ? 'Checked' : 'Generated'} ${ordered.length} ACP definitions in ${generated.size} files`
)
