async function checkOffline() {
  const text = (await readFile(resolve(output, outputFile), 'utf8')).replace(/\r\n/g, '\n')
  if (!text.startsWith(header)) {
    throw new Error(`Stale generated file: ${outputFile} (inputs or generator changed; regenerate)`)
  }
  const rest = text.slice(header.length)
  const newline = rest.indexOf('\n')
  if (!rest.startsWith(bodyDigestPrefix) || newline === -1) {
    throw new Error(`Stale generated file: ${outputFile} (missing body digest)`)
  }
  if (rest.slice(bodyDigestPrefix.length, newline) !== sha256(rest.slice(newline + 1))) {
    throw new Error(`Generated file was edited by hand: ${outputFile}`)
  }
  for (const file of await readdir(output)) {
    if ((file.endsWith('.gen.ts') || file.endsWith('.generated.ts')) && file !== outputFile) {
      throw new Error(`Unexpected generated file: ${file}`)
    }
  }
  console.log(`Checked ${outputFile} against pinned inputs offline`)
}
if (check && !checkOnline) {
  await checkOffline()
  process.exit(0)
}

async function download(url, digest) {
  const response = await fetch(url)
  if (!response.ok) {
    throw new Error(`Download failed: ${url} (${response.status})`)
  }
  const text = await response.text()
  if (createHash('sha256').update(text).digest('hex') !== digest) {
    throw new Error(`Upstream content changed: ${url}`)
  }
  return text
}

